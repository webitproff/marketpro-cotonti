 * ============================================================
 *
 * Хук `footer.first` в Cotonti вызывается на раннем этапе формирования
 * подвала (footer) страницы. Он позволяет модулям и плагинам динамически
 * изменить переменные окружения, чтобы подключить нужный шаблон подвала.
 *
 * Файл market.footer.first.php отвечает за выбор footer-шаблона для модуля Market.
 * Он анализирует текущий URL и определяет, какому товару или категории
 * соответствует просматриваемая страница, после чего устанавливает
 * `Cot::$env['location']` для загрузки специфичного шаблона подвала.
 *
 * Логика аналогична market.header.first.php, но для футера.
 *
 * Source and updates   https://github.com/webitproff/marketpro-cotonti
 * ReadMeMore:          https://abuyfile.com/ru/market/cotonti/plugs/marketpro
