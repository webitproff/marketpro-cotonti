// Защита от прямого вызова файла
defined('COT_CODE') or die('Wrong URL.');

// Проверяем, что текущее расширение (модуль) является 'market'.
// Если нет, то дальнейшая обработка не требуется.
if (Cot::$env['ext'] !== 'market') {
    return;
}

// Подключаем главный файл модуля Market, чтобы получить доступ к функциям
// проверки существования шаблонов подвала (market_cat_has_footer_tpl и др.).
require_once cot_incfile('market', 'module');

/* ---------------------------------------------------------------------
 * БАЗОВОЕ ЗНАЧЕНИЕ location
 * ---------------------------------------------------------------------
 * Устанавливаем location по умолчанию для корня модуля Market.
 * Если специфический шаблон подвала не будет найден, останется это значение.
 * --------------------------------------------------------------------- */
Cot::$env['location'] = 'market';

/* =====================================================================
 * 1. ОПРЕДЕЛЕНИЕ ПО ID ТОВАРА (ЧИСЛОВОЙ ИДЕНТИФИКАТОР)
 * ===================================================================== */
// Проверяем, передан ли параметр 'id' в GET-запросе
if (!empty($_GET['id'])) {
    // Приводим значение к целому числу, чтобы избежать SQL-инъекций
    $id = (int)$_GET['id'];

    // Если ID положительный, продолжаем
    if ($id > 0) {
        // Запрашиваем код категории товара по его ID
        $cat = Cot::$db->query(
            "SELECT fieldmrkt_cat FROM " . Cot::$db->market . " WHERE fieldmrkt_id = ? LIMIT 1",
            [$id]
        )->fetchColumn();

        // Если категория найдена
        if ($cat) {
            // Проверяем наличие специализированного footer-шаблона для товара
            // Например, footer.market.<cat>.pagehasid.tpl
            if (market_cat_has_footer_tpl_pageid($cat)) {
                // Устанавливаем location для специализированного шаблона
                Cot::$env['location'] = 'market.' . $cat . '.pagehasid';
                // Сбрасываем ext, чтобы система использовала location
                Cot::$env['ext'] = '';
                return;
            }
            // Если специализированного нет, проверяем общий шаблон категории
            // Например, footer.market.<cat>.tpl
            if (market_cat_has_footer_tpl($cat)) {
                Cot::$env['location'] = 'market.' . $cat;
                Cot::$env['ext'] = '';
                return;
            }
        }
    }
}

/* =====================================================================
 * 2. ОПРЕДЕЛЕНИЕ ПО АЛИАСУ ТОВАРА (ЧПУ)
 * ===================================================================== */
// Проверяем, передан ли параметр 'al' (алиас)
if (!empty($_GET['al'])) {
    // Безопасно извлекаем алиас
    $al = cot_import('al', 'G', 'TXT');

    // Если алиас не пустой
    if ($al) {
        // Запрашиваем код категории товара по алиасу
        $cat = Cot::$db->query(
            "SELECT fieldmrkt_cat FROM " . Cot::$db->market . " WHERE fieldmrkt_alias = ? LIMIT 1",
            [$al]
        )->fetchColumn();

        // Если категория найдена
        if ($cat) {
            // Проверяем специализированный шаблон для товара
            if (market_cat_has_footer_tpl_pageid($cat)) {
                Cot::$env['location'] = 'market.' . $cat . '.pagehasid';
                Cot::$env['ext'] = '';
                return;
            }
            // Проверяем общий шаблон категории
            if (market_cat_has_footer_tpl($cat)) {
                Cot::$env['location'] = 'market.' . $cat;
                Cot::$env['ext'] = '';
                return;
            }
        }
    }
}

/* =====================================================================
 * 3. ОПРЕДЕЛЕНИЕ ПО URL-СЕГМЕНТАМ (СПИСКИ КАТЕГОРИЙ)
 * ===================================================================== */
// Если нет ни ID, ни алиаса, пробуем разобрать URL
if (empty($_GET['id']) && empty($_GET['al'])) {
    // Получаем текущий URI и обрезаем ведущие/замыкающие слэши
    $uri = trim($_SERVER['REQUEST_URI'] ?? '', '/');
    // Разбиваем URI на сегменты по слэшу
    $segments = explode('/', $uri);

    // Если первый сегмент является двухбуквенным языковым кодом (например, 'ru', 'en'),
    // убираем его, чтобы не мешал определению категории
    if (isset($segments[0]) && strlen($segments[0]) == 2 && ctype_alpha($segments[0])) {
        array_shift($segments);
    }

    // Проверяем, что первый значимый сегмент — 'market'
    if (!empty($segments[0]) && $segments[0] === 'market') {
        // Идём с конца сегментов к началу, чтобы самая вложенная категория имела приоритет
        for ($i = count($segments) - 1; $i >= 1; $i--) {
            $possibleCat = $segments[$i];
            // Если для возможной категории существует footer-шаблон
            if (market_cat_has_footer_tpl($possibleCat)) {
                // Устанавливаем location для этой категории
                Cot::$env['location'] = 'market.' . $possibleCat;
                Cot::$env['ext'] = '';
                return;
            }
        }
    }
}

/* =====================================================================
 * 4. СТАРЫЙ СПОСОБ ЧЕРЕЗ ПАРАМЕТР ?c=
 * ===================================================================== */
// Если используется старый формат с параметром 'c'
if (!empty($_GET['c'])) {
    // Безопасно получаем значение
    $c = cot_import('c', 'G', 'TXT');
    // Если значение задано и для него есть шаблон
    if ($c && market_cat_has_footer_tpl($c)) {
        Cot::$env['location'] = 'market.' . $c;
        Cot::$env['ext'] = '';
        return;
    }
}

/* ---------------------------------------------------------------------
 * ФИНАЛЬНОЕ ДЕЙСТВИЕ
 * ---------------------------------------------------------------------
 * Если ни одно условие не сработало, оставляем location='market',
 * сбрасываем ext, чтобы загрузился общий footer.market.tpl
 * (или стандартный, если и его нет).
 * --------------------------------------------------------------------- */
Cot::$env['ext'] = '';