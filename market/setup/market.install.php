    $result = cot_structure_add('market', [
        'structure_area'   => 'market',
        'structure_code'   => $cat['code'],
        'structure_title'  => $cat['title'],
        'structure_desc'   => $cat['desc'],
        'structure_path'   => $cat['path'],
        'structure_locked' => 0,
        'structure_count'  => 0,
