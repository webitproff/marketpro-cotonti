defined('COT_CODE') or die('Wrong URL');

// В Cotonti доступ к базе данных и её таблицам обычно осуществляется через статический объект Cot::$db.
// Не требуется объявлять глобальные переменные $db, $db_auth, $db_structure, $db_market,
// если в вашем модуле используется регистрация таблиц через Cot::$db->registerTable().

// -------------------------------------------------------------------------
// 1. Удаляем все записи прав доступа, связанные с модулем market.
// Права хранятся в таблице прав доступа (cot_auth), поле auth_code указывает модуль.
// Мы удаляем все строки, у которых auth_code = 'market', чтобы не осталось «мусорных» прав.
// Используем метод delete() объекта Cot::$db, передавая имя таблицы Cot::$db->auth.
// -------------------------------------------------------------------------
Cot::$db->delete(Cot::$db->auth, "auth_code = 'market'");

// -------------------------------------------------------------------------
// 2. Удаляем все категории структуры, принадлежащие модулю market.
// Категории хранятся в таблице структуры (cot_structure), поле structure_area определяет область.
// Удаляем все записи, где structure_area = 'market', что охватывает и родительские, и дочерние категории.
// Имя таблицы структуры берём из Cot::$db->structure.
// -------------------------------------------------------------------------
Cot::$db->delete(Cot::$db->structure, "structure_area = 'market'");

// -------------------------------------------------------------------------
// 3. Удаляем таблицу товаров модуля.
// Имя таблицы зарегистрировано через Cot::$db->registerTable('market') в market.functions.php,
// поэтому оно доступно как Cot::$db->market.
// Проверяем наличие этого свойства перед удалением, чтобы избежать ошибок,
// если модуль не был установлен полностью.
// -------------------------------------------------------------------------
if (isset(Cot::$db->market)) {
    // Выполняем SQL-запрос DROP TABLE IF EXISTS — таблица удалится только если существует.
    // Обратные кавычки вокруг имени таблицы защищают от возможных конфликтов с зарезервированными словами.
    // Используем конкатенацию строк, как в ваших функциях, а не интерполяцию с фигурными скобками.
    Cot::$db->query('DROP TABLE IF EXISTS `' . Cot::$db->market . '`');
}

// -------------------------------------------------------------------------
// 4. Очищаем кэш прав пользователей.
// Функция cot_auth_clear() сбрасывает сохранённые права в таблице cot_users.
// Вызов с параметром 'all' (значение по умолчанию) очищает кэш для всех пользователей,
// а также удаляет гостевой кэш из Cot::$cache.
// Это необходимо, чтобы изменения прав (удаление записей из cot_auth) вступили в силу немедленно.
// -------------------------------------------------------------------------
cot_auth_clear('all');
