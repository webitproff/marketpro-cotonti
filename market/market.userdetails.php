$t->assign([
    'USERS_DETAILS_MARKET_COUNT' => $market_count_all,
    'USERS_DETAILS_MARKET_TAB_URL' => cot_url('users', ['m' => 'details', 'id' => $urr['user_id'], 'u' => $urr['user_name'], 'tab' => 'market']),
	'MARKET_VENDOR_SHOWCASE_URL' => cot_url('market', ['m' => 'vendor', 'u' => $urr['user_name']]),
]);

// Присваиваем сгенерированный HTML вкладки переменной MARKET
$t->assign('MARKET', $t1->text('MAIN'));