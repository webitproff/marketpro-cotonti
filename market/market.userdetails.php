/**
 * ============================================================
 * ДОКУМЕНТАЦИЯ ПО ХУКУ `users.details.tags` И ФАЙЛУ market.userdetails.php
 * ============================================================
 *
 * Хук `users.details.tags` в Cotonti вызывается на странице профиля
 * пользователя (users.php?m=details&id=...). Он позволяет расширять
 * содержимое вкладок профиля, добавляя свои данные и разметку.
 *
 * Файл market.userdetails.php отвечает за вывод вкладки «Товары»
 * в профиле пользователя. Он обрабатывает:
 *   - отображение списка товаров пользователя;
 *   - фильтрацию по категориям;
 *   - постраничную навигацию;
 *   - AJAX-подгрузку списка товаров без перезагрузки страницы;
 *   - удаление товаров (для администраторов) с подтверждением.
 *
 * Всё содержимое вкладки генерируется в переменную `MARKET`, которая
 * затем выводится в основном шаблоне профиля.
 *
 * Source and updates   https://github.com/webitproff/marketpro-cotonti
 * ReadMeMore:          https://abuyfile.com/ru/market/cotonti/plugs/marketpro
 * Support:             https://abuyfile.com/ru/forums/cotonti/custom/marketpro
 *
 * Date: Sep 10, 2026
 *
 * @package market
 * @version 5.7.9
 * @author webitproff
 * @copyright Copyright (c) webitproff 2026 | https://github.com/webitproff/marketpro-cotonti
 * @license BSD
 */

// Защита от прямого вызова файла
defined('COT_CODE') or die('Wrong URL');

// Подключаем класс словаря Market для использования констант статусов
use cot\modules\market\inc\MarketDictionary;

// Подключаем главный файл модуля Market, чтобы получить доступ к его функциям и языковым строкам
require_once cot_incfile('market', 'module');

/* =====================================================================
 * ОПРЕДЕЛЕНИЕ КОЛИЧЕСТВА ТОВАРОВ НА СТРАНИЦУ
 * ---------------------------------------------------------------------
 * Получаем настройку количества товаров для категории по умолчанию.
 * Используется для пагинации и AJAX-подгрузки.
 * ===================================================================== */
// Если задан параметр 'marketmaxlistsperpageincat' для категории по умолчанию, берём его,
// иначе пробуем 'marketmaxlistsperpage', иначе значение по умолчанию 10.
$perpageincat = isset(Cot::$cfg['market']['cat___default']['marketmaxlistsperpageincat'])
    ? Cot::$cfg['market']['cat___default']['marketmaxlistsperpageincat']
    : (Cot::$cfg['market']['cat___default']['marketmaxlistsperpage'] ?? 10);

/* =====================================================================
 * ОБРАБОТКА AJAX-ЗАПРОСА
 * ---------------------------------------------------------------------
 * Если в GET-запросе присутствует параметр `ajax=1`, значит страница
 * запрошена асинхронно для подгрузки следующей порции товаров.
 * В этом случае формируем JSON-ответ и завершаем выполнение.
 * ===================================================================== */
// Проверяем, является ли текущий запрос AJAX-запросом
if (cot_import('ajax', 'G', 'INT') == 1) {
    // Объявляем глобальные переменные, используемые в этом блоке
    global $usr, $urr, $db_market;

    // Получаем текущую вкладку
    $tab = cot_import('tab', 'G', 'ALP');
    // Если вкладка 'market', получаем код категории, иначе пустая строка
    $category = ($tab == 'market') ? cot_import('cat', 'G', 'TXT') : '';
    // Получаем смещение (номер начальной записи) для пагинации
    $d = cot_import('dmarket', 'G', 'INT');

    // Инициализируем массивы для условий WHERE и сортировки ORDER
    $where = [];
    $order = [];

    // Если пользователь не авторизован или просматривает чужой профиль и не админ,
    // то отображаем только опубликованные товары
    if ($usr['id'] == 0 || ($usr['id'] != $urr['user_id'] && !$usr['isadmin'])) {
        $where['state'] = 'fieldmrkt_state = ' . MarketDictionary::STATE_PUBLISHED;
    }

    // Если задана категория, добавляем условие по коду категории
    if ($category) {
        $where['cat'] = 'fieldmrkt_cat = ' . Cot::$db->quote($category);
    }

    // Добавляем условие отбора по владельцу – просматриваемому пользователю
    $where['owner'] = 'fieldmrkt_ownerid = ' . (int)$urr['user_id'];

    // Устанавливаем сортировку по дате добавления в обратном порядке
    $order['date'] = 'fieldmrkt_date DESC';

    /* === Hook === */
    // Даём плагинам возможность изменить условия запроса
    foreach (cot_getextplugins('market.userdetails.query') as $pl) {
        include $pl;
    }
    /* ===== */

    // Формируем SQL-строку WHERE из массива условий
    $where_sql = $where ? 'WHERE ' . implode(' AND ', $where) : '';
    // Формируем SQL-строку ORDER BY
    $order_sql = $order ? 'ORDER BY ' . implode(', ', $order) : '';

    // Выполняем запрос для получения общего количества товаров
    $totalitems = Cot::$db->query("SELECT COUNT(*) FROM $db_market AS m $where_sql")->fetchColumn();

    // Выполняем запрос для получения конкретной страницы товаров
    $sqllist = Cot::$db->query("SELECT * FROM $db_market AS m $where_sql $order_sql LIMIT $d, $perpageincat");
    // Получаем все строки результата
    $items = $sqllist->fetchAll();

    // Если товаров нет, возвращаем пустой JSON и завершаем
    if (empty($items)) {
        header('Content-Type: application/json');
        echo json_encode(['rows' => '', 'pagination' => '']);
        exit;
    }

    // Получаем список плагинов для хука market.userdetails.loop
    $extp_loop = cot_getextplugins('market.userdetails.loop');
    // Создаём экземпляр шаблона для AJAX-ответа (используется тот же шаблон userdetails)
    $ajax_tpl = new XTemplate(cot_tplfile(['market', 'userdetails'], 'module'));

    // Перебираем каждый товар
    foreach ($items as $item_data) {
        // Генерируем теги товара (MARKET_ROW_...)
        $tags = cot_generate_markettags($item_data, 'MARKET_ROW_', Cot::$cfg['market']['markettruncatetext'] ?? 0, $usr['isadmin'], Cot::$cfg['homebreadcrumb']);

        // Если у пользователя есть права на удаление, формируем соответствующие теги
        if (!empty($tags['MARKET_ROW_ADMIN_DELETE_URL'])) {
            // Параметры URL для возврата после удаления
            $urlParams = ['m' => 'details', 'id' => $urr['user_id'], 'u' => $urr['user_name'], 'tab' => 'market'];
            if ($category) $urlParams['cat'] = $category;
            if ($d > 0) $urlParams['dmarket'] = $d;
            // Формируем URL удаления с подтверждением
            $delUrl = cot_url('market', ['m' => 'edit', 'a' => 'update', 'delete' => '1', 'id' => $item_data['fieldmrkt_id'], 'x' => Cot::$sys['xk'], 'redirect' => base64_encode(cot_url('users', $urlParams, '', true))]);
            $delConfirm = cot_confirm_url($delUrl, 'market');
            $tags['MARKET_ROW_ADMIN_DELETE'] = cot_rc_link($delConfirm, Cot::$L['Delete'], 'class="confirmLink"');
            $tags['MARKET_ROW_ADMIN_DELETE_URL'] = $delConfirm;
        }

        // Вызываем плагины для дополнительной обработки тегов
        foreach ($extp_loop as $pl) include $pl;

        // Присваиваем теги шаблону и парсим блок MARKET_ROWS
        $ajax_tpl->assign($tags);
        $ajax_tpl->parse('MAIN.MARKET_ROWS');
    }

    // Получаем итоговый HTML списка товаров
    $rows_html = $ajax_tpl->text('MAIN.MARKET_ROWS');

    // Формируем параметры для пагинации
    $opt_array = ['m'=>'details', 'id'=>$urr['user_id'], 'u'=>$urr['user_name'], 'tab'=>'market'];
    if ($category) $opt_array['cat'] = $category;

    // Генерируем пагинацию
    $pagenav = cot_pagenav('users', $opt_array, $d, $totalitems, $perpageincat, 'dmarket');

    // Создаём шаблон для пагинации и заполняем его
    $pagination_tpl = new XTemplate(cot_tplfile(['market', 'pagination'], 'module'));
    $pagination_tpl->assign(cot_generatePaginationTags($pagenav));
    $pagination_tpl->parse('MAIN');
    $pagination_html = $pagination_tpl->text('MAIN');

    // Отправляем JSON-ответ
    header('Content-Type: application/json');
    echo json_encode(['rows' => $rows_html, 'pagination' => $pagination_html]);
    exit;
}

/* =====================================================================
 * ОСНОВНАЯ ЛОГИКА ОТОБРАЖЕНИЯ ВКЛАДКИ
 * ---------------------------------------------------------------------
 * Этот блок выполняется, когда страница профиля открыта обычным
 * способом (не через AJAX). Здесь формируется полное содержимое
 * вкладки «Товары»: список категорий, список товаров, пагинация.
 * ===================================================================== */

/* ---------------------------------------------------------------------
 * 1. ПОЛУЧЕНИЕ ПРАВ ПОЛЬЗОВАТЕЛЯ НА МОДУЛЬ MARKET
 * ---------------------------------------------------------------------
 * Функция cot_auth() возвращает массив из трёх элементов:
 *   - право на чтение (auth_read),
 *   - право на запись (auth_write),
 *   - флаг администратора (isadmin).
 * Параметры:
 *   'market' — код модуля,
 *   'any'    — область (любая категория),
 *   'RWA'    — требуемые права: R (чтение), W (запись), A (администрирование).
 * Результат присваивается соответствующим элементам массива $usr.
 * --------------------------------------------------------------------- */
list($usr['auth_read'], $usr['auth_write'], $usr['isadmin']) = cot_auth('market', 'any', 'RWA');

/* ---------------------------------------------------------------------
 * 2. ПОЛУЧЕНИЕ ТЕКУЩЕЙ ВКЛАДКИ И КАТЕГОРИИ
 * ---------------------------------------------------------------------
 * cot_import('tab', 'G', 'ALP') — безопасно извлекает параметр 'tab'
 * из GET-запроса. 'ALP' означает, что допускаются только буквы.
 * Значение сохраняется в $tab.
 * --------------------------------------------------------------------- */
$tab = cot_import('tab', 'G', 'ALP');

/* ---------------------------------------------------------------------
 * Если активна вкладка 'market' (то есть пользователь смотрит товары),
 * тогда извлекаем параметр 'cat' (код категории) из GET. Если вкладка
 * не 'market', категория не нужна — присваиваем пустую строку.
 * --------------------------------------------------------------------- */
$category = ($tab == 'market') ? cot_import('cat', 'G', 'TXT') : '';

/* ---------------------------------------------------------------------
 * 3. ПОЛУЧЕНИЕ ПАРАМЕТРОВ ПАГИНАЦИИ
 * ---------------------------------------------------------------------
 * cot_import_pagenav() обрабатывает параметр постраничной навигации.
 *   Входные параметры:
 *     'dmarket' — имя GET-параметра, отвечающего за смещение,
 *     $perpageincat — количество элементов на страницу.
 *   Возвращает массив из трёх значений:
 *     $pg    — текущая страница (обычно не используется),
 *     $d     — смещение для SQL LIMIT (номер начальной записи),
 *     $durl  — строка для добавления в URL (если нужно).
 * Здесь мы используем $d и $durl.
 * --------------------------------------------------------------------- */
list($pg, $d, $durl) = cot_import_pagenav('dmarket', $perpageincat);

/* ---------------------------------------------------------------------
 * 4. СОЗДАНИЕ ОСНОВНОГО ШАБЛОНА ВКЛАДКИ
 * ---------------------------------------------------------------------
 * cot_tplfile(['market', 'userdetails'], 'module') — возвращает путь
 * к файлу шаблона userdetails.tpl модуля market. Новый экземпляр
 * XTemplate создаётся на основе этого файла. Шаблон будет использоваться
 * для вывода всех элементов вкладки.
 * --------------------------------------------------------------------- */
$t1 = new XTemplate(cot_tplfile(['market', 'userdetails'], 'module'));

/* ---------------------------------------------------------------------
 * 5. ПЕРЕДАЧА БАЗОВЫХ ПЕРЕМЕННЫХ В ШАБЛОН
 * ---------------------------------------------------------------------
 * В шаблон передаются два значения:
 *   MARKET_ADD_URL — ссылка на страницу добавления товара,
 *   MARKET_ADD_SHOWBUTTON — флаг, показывать ли кнопку добавления
 *                           (true, если у пользователя есть право записи).
 * --------------------------------------------------------------------- */
$t1->assign([
    'MARKET_ADD_URL' => cot_url('market', 'm=add'),
    'MARKET_ADD_SHOWBUTTON' => $usr['auth_write'] ? true : false,
	'MARKET_TAB_URL' => cot_url('users', ['m' => 'details', 'id' => $urr['user_id'], 'u' => $urr['user_name'], 'tab' => 'market']),
]);

/* ---------------------------------------------------------------------
 * 6. ИНИЦИАЛИЗАЦИЯ МАССИВОВ УСЛОВИЙ И СОРТИРОВКИ
 * ---------------------------------------------------------------------
 * $where — массив строк, которые будут объединены в SQL-условие WHERE,
 * $order — массив строк для сортировки ORDER BY.
 * --------------------------------------------------------------------- */
$where = [];
$order = [];

/* ---------------------------------------------------------------------
 * 7. УСЛОВИЕ ПО СТАТУСУ ТОВАРА
 * ---------------------------------------------------------------------
 * Если текущий пользователь не авторизован (id == 0) ИЛИ
 * (он просматривает не свой профиль И не является администратором),
 * то показываем только опубликованные товары (state = STATE_PUBLISHED).
 * Для владельца профиля или администратора ограничение не действует,
 * они видят все статусы (например, черновики, на модерации).
 * --------------------------------------------------------------------- */
if ($usr['id'] == 0 || ($usr['id'] != $urr['user_id'] && !$usr['isadmin'])) {
    $where['state'] = 'fieldmrkt_state = ' . MarketDictionary::STATE_PUBLISHED;
}

/* ---------------------------------------------------------------------
 * 8. УСЛОВИЕ ПО КАТЕГОРИИ
 * ---------------------------------------------------------------------
 * Если пользователь выбрал конкретную категорию ($category не пуста),
 * добавляем условие отбора по полю fieldmrkt_cat.
 * Cot::$db->quote() экранирует строку для безопасного использования в SQL.
 * --------------------------------------------------------------------- */
if ($category) {
    $where['cat'] = 'fieldmrkt_cat = ' . Cot::$db->quote($category);
}

/* ---------------------------------------------------------------------
 * 9. УСЛОВИЕ ПО ВЛАДЕЛЬЦУ
 * ---------------------------------------------------------------------
 * Отбираем только те товары, которые принадлежат просматриваемому
 * пользователю. $urr['user_id'] — ID пользователя из профиля.
 * Значение приводится к целому числу для безопасности.
 * --------------------------------------------------------------------- */
$where['owner'] = 'fieldmrkt_ownerid = ' . (int)$urr['user_id'];

/* ---------------------------------------------------------------------
 * 10. СОРТИРОВКА
 * ---------------------------------------------------------------------
 * Устанавливаем сортировку по дате добавления товара по убыванию
 * (самые новые сначала).
 * --------------------------------------------------------------------- */
$order['date'] = 'fieldmrkt_date DESC';

/* ---------------------------------------------------------------------
 * 11. СОЗДАНИЕ КОПИИ УСЛОВИЙ ДЛЯ ПОДСЧЁТА КАТЕГОРИЙ
 * ---------------------------------------------------------------------
 * Для вывода списка категорий с количеством товаров необходимо
 * подсчитать товары по каждой категории, но без фильтра по конкретной
 * категории (иначе все остальные категории не будут показаны).
 * Поэтому создаём копию $where в $wherecount и удаляем из неё
 * условие по категории, если оно было.
 * --------------------------------------------------------------------- */
$wherecount = $where;
if (isset($wherecount['cat'])) {
    unset($wherecount['cat']);
}

/* === Hook === */
/* ---------------------------------------------------------------------
 * 12. ХУК ДЛЯ МОДИФИКАЦИИ УСЛОВИЙ
 * ---------------------------------------------------------------------
 * Позволяет другим плагинам изменить массивы $where, $wherecount, $order
 * перед выполнением запросов. Подключаются все файлы, зарегистрированные
 * на хук 'market.userdetails.query'.
 * --------------------------------------------------------------------- */
foreach (cot_getextplugins('market.userdetails.query') as $pl) {
    include $pl;
}
/* ===== */

/* ---------------------------------------------------------------------
 * 13. ОЧИСТКА МАССИВОВ ОТ ПУСТЫХ ЭЛЕМЕНТОВ
 * ---------------------------------------------------------------------
 * array_filter() удаляет из массива все элементы, которые равны false
 * (например, пустые строки или null). Это нужно, если плагины удалили
 * какие-то условия, оставив пустые значения.
 * --------------------------------------------------------------------- */
$where = array_filter($where);
$wherecount = array_filter($wherecount);

/* ---------------------------------------------------------------------
 * 14. ФОРМИРОВАНИЕ SQL-СТРОК
 * ---------------------------------------------------------------------
 * $where_sql — строка WHERE для основного запроса (с фильтром категории).
 * $wherecount_sql — строка WHERE для запроса подсчёта по категориям
 *                   (без фильтра категории).
 * $order_sql — строка ORDER BY.
 * implode(' AND ', $where) соединяет элементы массива через " AND ".
 * --------------------------------------------------------------------- */
$where_sql = $where ? 'WHERE ' . implode(' AND ', $where) : '';
$wherecount_sql = $wherecount ? 'WHERE ' . implode(' AND ', $wherecount) : '';
$order_sql = $order ? 'ORDER BY ' . implode(', ', $order) : '';

/* ---------------------------------------------------------------------
 * 15. ЗАПРОС: КОЛИЧЕСТВО ТОВАРОВ ПО КАТЕГОРИЯМ
 * ---------------------------------------------------------------------
 * Выполняется SQL-запрос, который выбирает код категории (fieldmrkt_cat)
 * и количество товаров в ней (COUNT(fieldmrkt_cat) as cat_count) из таблицы
 * товаров $db_market с условиями $wherecount_sql (без конкретной категории).
 * Группировка по полю fieldmrkt_cat.
 * Результат fetchAll() возвращает массив строк, каждая из которых содержит
 * код категории и количество товаров.
 * --------------------------------------------------------------------- */
$sql_market_count_cat = Cot::$db->query(
    "SELECT fieldmrkt_cat, COUNT(fieldmrkt_cat) as cat_count 
     FROM $db_market 
     $wherecount_sql 
     GROUP BY fieldmrkt_cat"
)->fetchAll();

/* ---------------------------------------------------------------------
 * 16. ЗАПРОС: ОБЩЕЕ КОЛИЧЕСТВО ТОВАРОВ ПОЛЬЗОВАТЕЛЯ
 * ---------------------------------------------------------------------
 * Выполняется запрос для подсчёта всех товаров пользователя (по условиям
 * $wherecount_sql, т.е. без фильтра категории, но с учётом статуса и владельца).
 * fetchColumn() возвращает первое значение первой строки — число товаров.
 * Это значение сохраняется в $market_count_all и $market_count.
 * $market_count_all будет использоваться для показа общего количества,
 * $market_count может измениться, если выбрана категория.
 * --------------------------------------------------------------------- */
$sql_market_count = Cot::$db->query("SELECT COUNT(*) FROM $db_market $wherecount_sql");
$market_count_all = $market_count = $sql_market_count->fetchColumn();

/* ---------------------------------------------------------------------
 * 17. ВЫЧИСЛЕНИЕ ДАННЫХ ДЛЯ КНОПКИ "ЗАГРУЗИТЬ ЕЩЁ"
 * ---------------------------------------------------------------------
 * $totalpages — общее количество страниц, вычисляется как ceil(число товаров / на страницу).
 * $currentpage — текущая страница (начиная с 1), вычисляется как floor(смещение / на страницу) + 1.
 * Эти значения нужны для AJAX-подгрузки, чтобы понимать, есть ли ещё страницы.
 * --------------------------------------------------------------------- */
$totalpages = ceil($market_count / $perpageincat);
$currentpage = floor($d / $perpageincat) + 1;

/* ---------------------------------------------------------------------
 * 18. ПЕРЕДАЧА ДАННЫХ ДЛЯ AJAX-ПОДГРУЗКИ И ЛОКАЛИЗАЦИЯ
 * ---------------------------------------------------------------------
 * В шаблон передаются переменные:
 *   LOAD_MORE_URL — URL для AJAX-запроса следующей страницы. Содержит параметры
 *                   профиля пользователя, вкладки, категории и ajax=1.
 *   LOAD_MORE_PERPAGE — количество товаров на странице (для JavaScript).
 *   LOAD_MORE_TOTALPAGES — общее число страниц.
 *   LOAD_MORE_CURRENTPAGE — текущая страница.
 *   LOAD_MORE_LANG — JSON-строка с локализованными сообщениями для кнопки.
 *                   Используются языковые строки $L['market_load_more'],
 *                   $L['market_loading'], $L['market_load_error'] с fallback.
 * --------------------------------------------------------------------- */
$t1->assign([
    'LOAD_MORE_URL' => cot_url('users', [
        'm' => 'details',
        'id' => $urr['user_id'],
        'u' => $urr['user_name'],
        'tab' => 'market',
        'cat' => $category,
        'ajax' => 1
    ]),
    'LOAD_MORE_PERPAGE' => $perpageincat,
    'LOAD_MORE_TOTALPAGES' => $totalpages,
    'LOAD_MORE_CURRENTPAGE' => $currentpage,
    'LOAD_MORE_LANG' => json_encode([
        'load_more' => $L['market_load_more'] ?? 'Загрузить ещё (страница %d из %d)',
        'loading'   => $L['market_loading'] ?? '<i class="fa fa-spinner fa-spin"></i> Загрузка...',
        'error'     => $L['market_load_error'] ?? 'Ошибка загрузки. Попробуйте ещё раз.'
    ])
]);

// Выполняем запрос для получения списка товаров текущей страницы
$sqllist = Cot::$db->query("SELECT * FROM $db_market AS m
    $where_sql
    $order_sql
    LIMIT $d, $perpageincat");

/* =====================================================================
 * ВЫВОД КАТЕГОРИЙ В ШАБЛОНЕ
 * ---------------------------------------------------------------------
 * $sql_market_count_cat — массив, полученный ранее запросом, который
 * группирует товары по категориям и содержит поля:
 *   fieldmrkt_cat — код категории,
 *   cat_count     — количество товаров в этой категории.
 * Здесь мы перебираем этот массив, чтобы вывести каждую категорию
 * в виде строки (например, для фильтра по категориям).
 * ===================================================================== */
foreach ($sql_market_count_cat as $value) {
	
	global $db, $db_structure, $db_i18n4marketpro_structure;	
	
	$category_code = $value['fieldmrkt_cat'];
	$page_category_name = '';
	$current_locale = Cot::$usr['lang'];

	if (!empty($category_code)) {

		if (cot_plugin_active('i18n4marketpro') && $current_locale !== Cot::$cfg['defaultlang']) {

			$cat_translation = $db->query(
				"SELECT istructure_title FROM $db_i18n4marketpro_structure
				 WHERE istructure_code = ? AND istructure_locale = ?",
				[$category_code, $current_locale]
			)->fetchColumn();

			if ($cat_translation) {
				$page_category_name = htmlspecialchars($cat_translation, ENT_QUOTES, 'UTF-8');
			}
		}

		if (empty($page_category_name)) {
			$category_name_result = $db->query(
				"SELECT structure_title FROM $db_structure WHERE structure_code = ? AND structure_area = 'market'",
				[$category_code]
			)->fetchColumn();

			$page_category_name = !empty($category_name_result)
				? htmlspecialchars($category_name_result, ENT_QUOTES, 'UTF-8')
				: htmlspecialchars($category_code, ENT_QUOTES, 'UTF-8');
		}
	}
    /* -----------------------------------------------------------------
     * Формируем массив тегов для текущей категории и передаём их
     * в шаблон через $t1->assign().
     * ----------------------------------------------------------------- */
    $t1->assign([

        /* --------------------------------------------------------------
         * MARKET_CAT_ROW_TITLE — название категории.
         * Берется из структуры категорий Market (Cot::$structure['market']).
         * Если категория не найдена (например, была удалена), используется
         * пустая строка, чтобы избежать ошибок в шаблоне.
         * -------------------------------------------------------------- */
        //'MARKET_CAT_ROW_TITLE' => Cot::$structure['market'][$value['fieldmrkt_cat']]['title'] ?? '',
		'MARKET_CAT_ROW_TITLE' => $page_category_name,

        /* --------------------------------------------------------------
         * MARKET_CAT_ROW_ICON — иконка категории.
         * Аналогично берётся из структуры. Если иконки нет, пустая строка.
         * -------------------------------------------------------------- */
        'MARKET_CAT_ROW_ICON' => Cot::$structure['market'][$value['fieldmrkt_cat']]['icon'] ?? '',

        /* --------------------------------------------------------------
         * MARKET_CAT_ROW_URL — ссылка на профиль пользователя с выбранной
         * категорией. Формируется через cot_url() с параметрами:
         *   m=details, id, u, tab=market, cat=<код категории>.
         * Это позволяет перейти к просмотру только товаров этой категории.
         * -------------------------------------------------------------- */
        'MARKET_CAT_ROW_URL' => cot_url('users', [
            'm' => 'details',
            'id' => $urr['user_id'],
            'u' => $urr['user_name'],
            'tab' => 'market',
            'cat' => $value['fieldmrkt_cat']
        ]),

        /* --------------------------------------------------------------
         * MARKET_CAT_ROW_COUNT_MARKET — количество товаров в категории.
         * Берётся из результата SQL-запроса cat_count.
         * -------------------------------------------------------------- */
        'MARKET_CAT_ROW_COUNT_MARKET' => $value['cat_count'],

        /* --------------------------------------------------------------
         * MARKET_CAT_ROW_SELECT — признак, является ли эта категория
         * активной (выбранной пользователем). Если $category (выбранная
         * категория) совпадает с кодом текущей категории, то ставим 1,
         * иначе пустая строка. В шаблоне это может использоваться для
         * подсветки активной категории.
         * -------------------------------------------------------------- */
        'MARKET_CAT_ROW_SELECT' => ($category && $category == $value['fieldmrkt_cat']) ? 1 : '',
    ]);

    /* -----------------------------------------------------------------
     * Парсим блок MAIN.CAT_ROW в шаблоне $t1. Это обрабатывает фрагмент
     * шаблона, отвечающий за одну строку категории, и добавляет его
     * к общему выводу.
     * ----------------------------------------------------------------- */
    $t1->parse('MAIN.CAT_ROW');
}

/* ---------------------------------------------------------------------
 * ФОРМИРОВАНИЕ ПАРАМЕТРОВ URL ДЛЯ ПАГИНАЦИИ
 * ---------------------------------------------------------------------
 * Создаём массив $opt_array с базовыми параметрами для ссылок пагинации.
 * Эти параметры будут добавляться к URL страниц пагинации, чтобы
 * сохранить контекст (пользователь, вкладка, возможно категория).
 * --------------------------------------------------------------------- */
$opt_array = [
    'm' => 'details',              // модуль users, метод details
    'id' => $urr['user_id'],       // ID просматриваемого пользователя
    'u' => $urr['user_name'],      // имя пользователя для ЧПУ
    'tab' => 'market',             // активная вкладка "Товары"
];

/* ---------------------------------------------------------------------
 * Если пользователь выбрал конкретную категорию ($category не пуста),
 * то необходимо:
 *   1. Скорректировать общее количество товаров $market_count,
 *      чтобы пагинация строилась только по товарам этой категории.
 *      Для этого ищем в массиве $sql_market_count_cat элемент с кодом
 *      категории, равным $category, и берём из него cat_count.
 *      Если вдруг такой категории нет (например, ошибка), оставляем
 *      предыдущее значение $market_count.
 *   2. Добавить параметр 'cat' в массив $opt_array, чтобы пагинация
 *      сохраняла выбранную категорию в URL.
 * --------------------------------------------------------------------- */
if ($category) {
    // Поиск индекса категории в массиве результатов
    $categoryIndex = array_search($category, array_column($sql_market_count_cat, 'fieldmrkt_cat'));
    // Если нашли, берём cat_count, иначе оставляем текущее $market_count
    $market_count = ($categoryIndex !== false)
        ? $sql_market_count_cat[$categoryIndex]['cat_count']
        : $market_count;
    // Добавляем параметр категории в URL пагинации
    $opt_array['cat'] = $category;
}

/* ---------------------------------------------------------------------
 * ГЕНЕРАЦИЯ ПАГИНАЦИИ
 * ---------------------------------------------------------------------
 * cot_pagenav() генерирует структуру постраничной навигации.
 * Параметры:
 *   'users' — модуль, для которого строятся ссылки;
 *   $opt_array — дополнительные параметры URL;
 *   $d — текущее смещение (начальная запись для LIMIT);
 *   $market_count — общее количество элементов;
 *   $perpageincat — количество элементов на страницу;
 *   'dmarket' — имя GET-параметра для номера страницы.
 * Возвращает массив с данными для отображения страниц.
 * --------------------------------------------------------------------- */
$pagenav = cot_pagenav('users', $opt_array, $d, $market_count, $perpageincat, 'dmarket');

/* ---------------------------------------------------------------------
 * cot_generatePaginationTags($pagenav) преобразует массив пагинации
 * в набор тегов (PAGENAV_PAGES, PAGENAV_PREV, PAGENAV_NEXT и т.д.)
 * и присваивает их шаблону $t1. После этого в шаблоне можно использовать
 * соответствующие плейсхолдеры для вывода пагинации.
 * --------------------------------------------------------------------- */
$t1->assign(cot_generatePaginationTags($pagenav));

/* ---------------------------------------------------------------------
 * ПОЛУЧЕНИЕ СПИСКА ТОВАРОВ ДЛЯ ОТОБРАЖЕНИЯ
 * ---------------------------------------------------------------------
 * $sqllist — это объект PDOStatement, созданный ранее запросом,
 * который выбирает товары с учётом пагинации (LIMIT $d, $perpageincat).
 * Здесь мы извлекаем все строки результата в массив $sqllist_rowset.
 * Каждая строка — это ассоциативный массив с данными одного товара.
 * --------------------------------------------------------------------- */
$sqllist_rowset = $sqllist->fetchAll();

/* === Hook === */
/* ---------------------------------------------------------------------
 * Получаем список плагинов, привязанных к хуку market.userdetails.loop.
 * Эти плагины будут выполняться для каждой строки товара, позволяя
 * модифицировать данные или добавлять новые теги.
 * Результат сохраняется в переменную $extp.
 * --------------------------------------------------------------------- */
$extp = cot_getextplugins('market.userdetails.loop');
/* ===== */

/* =====================================================================
 * ВЫВОД ТОВАРОВ
 * ---------------------------------------------------------------------
 * Начинаем цикл по каждой записи из результата запроса $sqllist_rowset.
 * Каждая запись — это массив $item_data с данными одного товара.
 * ===================================================================== */
foreach ($sqllist_rowset as $item_data) {
    /* -----------------------------------------------------------------
     * Генерация набора тегов для текущего товара.
     * Функция cot_generate_markettags() формирует ассоциативный массив
     * тегов вида 'MARKET_ROW_...' на основе данных товара.
     * Параметры:
     *   $item_data — массив с данными товара из БД;
     *   'MARKET_ROW_' — префикс для тегов;
     *   Cot::$cfg['market']['markettruncatetext'] ?? 0 — максимальная длина
     *        обрезаемого текста (если 0, обрезка отключена);
     *   Cot::$usr['isadmin'] — флаг администратора;
     *   Cot::$cfg['homebreadcrumb'] — настройка хлебных крошек.
     * Возвращает массив тегов, который мы сохраняем в $marketTags.
     * ----------------------------------------------------------------- */
    $marketTags = cot_generate_markettags(
        $item_data,
        'MARKET_ROW_',
        Cot::$cfg['market']['markettruncatetext'] ?? 0,
        Cot::$usr['isadmin'],
        Cot::$cfg['homebreadcrumb']
    );

    /* -----------------------------------------------------------------
     * Проверяем, был ли сгенерирован тег 'MARKET_ROW_ADMIN_DELETE_URL'.
     * Этот тег появляется только если текущий пользователь имеет право
     * на удаление данного товара (обычно администратор).
     * Если тег не пустой — формируем дополнительные теги для ссылки удаления.
     * ----------------------------------------------------------------- */
    if (!empty($marketTags['MARKET_ROW_ADMIN_DELETE_URL'])) {

        /* --------------------------------------------------------------
         * Копируем массив параметров $opt_array, который содержит базовые
         * параметры для URL страницы профиля (m, id, u, tab, возможно cat).
         * Они будут использованы для формирования адреса возврата после удаления.
         * -------------------------------------------------------------- */
        $urlParams = $opt_array;

        /* --------------------------------------------------------------
         * Если был параметр смещения страницы $durl (номер страницы в пагинации),
         * добавляем его в массив параметров, чтобы после удаления пользователь
         * вернулся на ту же страницу списка товаров.
         * -------------------------------------------------------------- */
        if ($durl > 0) {
            $urlParams['dmarket'] = $durl;
        }

        /* --------------------------------------------------------------
         * Формируем URL для удаления товара.
         * Используем cot_url() для создания ссылки на модуль market с параметрами:
         *   m=edit, a=update — указывают на обработчик редактирования с действием update;
         *   delete=1 — сигнализирует, что это запрос на удаление;
         *   id — идентификатор товара;
         *   x — токен безопасности (Cot::$sys['xk']) для защиты от CSRF;
         *   redirect — base64-кодированный URL для возврата после удаления.
         * -------------------------------------------------------------- */
        $deleteUrl = cot_url('market', [
            'm' => 'edit',
            'a' => 'update',
            'delete' => '1',
            'id' => $item_data['fieldmrkt_id'],
            'x' => Cot::$sys['xk'],
            'redirect' => base64_encode(cot_url('users', $urlParams, '', true)),
        ]);

        /* --------------------------------------------------------------
         * Генерируем URL с подтверждением удаления.
         * cot_confirm_url() оборачивает переданный URL в ссылку, которая
         * при клике показывает JavaScript-подтверждение (confirm).
         * Параметр 'market' указывает модуль для поиска языковой строки подтверждения.
         * -------------------------------------------------------------- */
        $deleteConfirmUrl = cot_confirm_url($deleteUrl, 'market');

        /* --------------------------------------------------------------
         * Формируем HTML-ссылку удаления с классом 'confirmLink'.
         * cot_rc_link() создаёт ссылку с текстом $L['Delete'] и атрибутами.
         * Результат сохраняем в тег 'MARKET_ROW_ADMIN_DELETE' для вывода в шаблоне.
         * -------------------------------------------------------------- */
        $marketTags['MARKET_ROW_ADMIN_DELETE'] = cot_rc_link($deleteConfirmUrl, Cot::$L['Delete'], 'class="confirmLink"');

        /* --------------------------------------------------------------
         * Также сохраняем окончательный URL с подтверждением в тег
         * 'MARKET_ROW_ADMIN_DELETE_URL' (перезаписываем исходный).
         * -------------------------------------------------------------- */
        $marketTags['MARKET_ROW_ADMIN_DELETE_URL'] = $deleteConfirmUrl;
    }

    /* -----------------------------------------------------------------
     * Присваиваем все сгенерированные теги шаблону $t1.
     * Теперь в шаблоне доступны переменные вида {MARKET_ROW_...}.
     * ----------------------------------------------------------------- */
    $t1->assign($marketTags);

    /* === Hook === */
    /* -----------------------------------------------------------------
     * Вызываем плагины, привязанные к хуку market.userdetails.loop.
     * Плагины могут модифицировать теги или добавить свои.
     * Переменная $extp была получена ранее через cot_getextplugins().
     * ----------------------------------------------------------------- */
    foreach ($extp as $pl) {
        include $pl;
    }
    /* ===== */

    /* -----------------------------------------------------------------
     * Парсим блок MAIN.MARKET_ROWS в шаблоне $t1.
     * Это означает, что для текущего товара будет обработан кусок шаблона,
     * обёрнутый в <!-- BEGIN: MARKET_ROWS --> ... <!-- END: MARKET_ROWS -->.
     * После парсинга вывод добавится в общий результат.
     * ----------------------------------------------------------------- */
    $t1->parse('MAIN.MARKET_ROWS');
}

// Финальный хук для модификации шаблона вкладки
