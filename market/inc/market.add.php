// ВНИМАНИЕ: переменная $usr_can_publish определяет, может ли текущий пользователь
// публиковать товар сразу (минуя очередь утверждения). Она используется в шаблоне
// в условии {PHP.usr_can_publish}, чтобы показать кнопку "Опубликовать".
// Вычисляется как true только для администраторов, если в настройках модуля включена
// автоматическая валидация (marketautovalidate).

$usr_can_publish = false;  // по умолчанию запрещено

if (Cot::$usr['isadmin']) {
    // Пользователь — администратор
    if (Cot::$cfg['market']['marketautovalidate']) {
        // Автовалидация (автоутверждение публикаций без моерации админа) включена — разрешаем публикацию
        $usr_can_publish = true;
    }
    // Дополнительно парсим блок ADMIN в шаблоне (если он определён).
    // Если этих тегов BEGIN: ADMIN и END: ADMIN в шаблоне нет, вызов $t->parse('MAIN.ADMIN') ничего не делает. 
	// $t->parse('MAIN.ADMIN') ищет в файле шаблона market.add.tpl вложенный блок, объявленный так:
	// 	<!-- BEGIN: ADMIN --><div>Контент для админов</div><!-- END: ADMIN -->
    // Если они есть, блок будет отрисован и вставлен в то место, где он прописан.
    // ВАЖНО: блок BEGIN: ADMIN ... END: ADMIN может быть только один раз в шаблоне.
    // Если требуется несколько мест с разными условиями для админов, используйте
    // условные теги типа 
    // 	<!-- IF {PHP.usr.maingrp} == 5 -->   <div>Контент для админов</div>    <!-- ENDIF -->
    // 	<!-- IF {PHP.usr.isadmin} -->        <div>Контент для админов</div>    <!-- ENDIF -->
    // 	<!-- IF {PHP.usr_can_publish} -->    <div>Контент для админов</div>    <!-- ENDIF -->
	
    $t->parse('MAIN.ADMIN');
}

// Финальный парсинг основного блока MAIN
$t->parse('MAIN');
