/**
 * Add store item.
 * Market PRO Module for CMF Cotonti, PHP v.8.5+, MySQL v.8.4
 * 
 * Filename: market.add.php
 *
 * Path:    modules/market/inc/market.add.php
 *
 * ============================================================
 * ДОКУМЕНТАЦИЯ ПО ФАЙЛУ market.add.php
 * ============================================================
 *
 * Назначение:
 *   Обрабатывает форму добавления нового товара в модуль Market.
 *   Выполняет проверку прав доступа, импорт данных из POST, валидацию,
 *   добавление записи в базу данных и редиректы в зависимости от
 *   выбранного действия (опубликовать, сохранить как черновик,
 *   отправить на модерацию или предпросмотр). Также подготавливает
 *   данные для отображения формы: значения по умолчанию или данные
 *   клонируемого товара, выбирает подходящий шаблон (общий или
 *   специфичный для категории), формирует теги формы и обрабатывает
 *   дополнительные поля (extrafields).
 *
 * Основные параметры URL:
 *   c=<код категории>       — код категории, в которую добавляется товар;
 *   id=<числовой ID>        — идентификатор (используется, если нужно);
 *   clone=<числовой ID>     — ID существующего товара для клонирования;
 *   a=add                   — действие: обработка отправленной формы.
 *
 * Поля формы (POST):
 *   ritemmarketcat           — код категории;
 *   ritemmarkettitle         — название товара;
 *   ritemmarketdesc          — краткое описание;
 *   ritemmarkettext          — полный текст;
 *   ritemmarketparser        — парсер текста;
 *   ritemmarketalias         — алиас (ЧПУ);
 *   ritemmarketmetatitle     — meta-заголовок;
 *   ritemmarketmetah1        — SEO H1;
 *   ritemmarketmetadesc      — meta-описание;
 *   ritemmarketpcod          — артикул/код товара;
 *   ritemmarketcostdflt      — цена по умолчанию;
 *   ritemmarketcostusd       — цена в USD;
 *   ritemmarketdate          — дата публикации;
 *   ritemmarketdatenow       — флаг "обновить дату";
 *   ritemmarketstate         — статус (0 — опубликован, 1 — на модерации, 2 — черновик);
 *   preview=1                — кнопка «Предпросмотр»;
 *   дополнительные поля вида ritemmarket<имя_поля>.
 *
 * Логика работы:
 *   1. Импортирует параметры из GET: id, c, a.
 *   2. Проверяет права пользователя на модуль Market и на запись.
 *   3. Устанавливает парсер по умолчанию и получает список парсеров.
 *   4. Если действие $a == 'add' — обрабатывает отправку формы:
 *      a) вызывает cot_shield_protect() для защиты от CSRF;
 *      b) импортирует данные через cot_market_import();
 *      c) обрабатывает нажатие кнопки «Предпросмотр» (сохраняет как черновик
 *         и редиректит на страницу просмотра);
 *      d) повторно проверяет права для выбранной категории;
 *      e) валидирует данные;
 *      f) при отсутствии ошибок добавляет товар и редиректит в зависимости
 *         от итогового статуса; при ошибках возвращает пользователя на форму.
 *   5. Если действие не 'add' — подготавливает форму:
 *      a) инициализирует массив $ritem значениями по умолчанию;
 *      b) при наличии параметра clone загружает данные товара из БД
 *         (для клонирования);
 *      c) подставляет категорию из GET, если она не задана;
 *      d) определяет шаблон формы: общий или специфичный для категории;
 *      e) проверяет права для выбранной категории (если она задана)
 *         или ищет доступные категории для пользователя;
 *      f) формирует хлебные крошки, подзаголовок, мета-теги;
 *      g) создаёт объект XTemplate с выбранным шаблоном;
 *      h) формирует массив тегов формы MARKETADD_*: категории, SEO-поля,
 *         основные поля, цены, владелец, дата;
 *      i) обрабатывает дополнительные поля (extrafields), если они есть,
 *         с флагом MARKETADD_HAS_EXTRAFIELDS;
 *      j) выводит сообщения, вызывает хуки, парсит шаблон и возвращает HTML.
 *
 * Используемые классы и сервисы:
 *   NotFoundHttpException  — импортирован для совместимости и возможных расширений
 *                            (в текущей версии файла не используется напрямую);
 *   MarketDictionary       — константы состояний товара (STATE_DRAFT и др.);
 *   MarketRepository       — импортирован для совместимости и возможных расширений
 *                            (в текущей версии файла не используется напрямую);
 *   MarketControlService   — импортирован для совместимости и возможных расширений
 *                            (в текущей версии файла не используется напрямую);
 *   UsersRepository        — импортирован для совместимости и возможных расширений
 *                            (в текущей версии файла не используется напрямую);
 *   XTemplate              — шаблонизатор вывода формы;
 *   cot_market_import()    — импорт данных товара из POST;
 *   cot_market_validate()  — валидация данных товара;
 *   cot_market_add()       — добавление товара в БД;
 *   cot_generate_markettags() — генерация тегов товара (не используется напрямую,
 *                               но задействован через шаблон).
 *
 * Хуки:
 *   market.add.first          — в самом начале, до основных проверок;
 *   market.add.add.first      — перед импортом данных из POST;
 *   market.add.add.import     — после импорта, до валидации;
 *   market.add.add.error      — после валидации (если есть ошибки);
 *   market.add.main           — после подготовки основных переменных и шаблона;
 *   market.add.tags           — перед финальным парсингом шаблона.
 *
 * Source and updates   https://github.com/webitproff/marketpro-cotonti
 * ReadMeMore:          https://abuyfile.com/ru/market/cotonti/plugs/marketpro
 * Support:             https://abuyfile.com/ru/forums/cotonti/custom/marketpro
