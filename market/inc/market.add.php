// Импортируем исключение для обработки не найденных страниц (используется при клонировании)
use cot\exceptions\NotFoundHttpException;

// Импортируем класс словаря Market для констант статусов
use cot\modules\market\inc\MarketDictionary;

// Импортируем репозиторий товаров для работы с БД (используется при клонировании)
use cot\modules\market\inc\MarketRepository;

// Импортируем сервис управления товарами (удаление и т.п.)
use cot\modules\market\inc\MarketControlService;

// Импортируем репозиторий пользователей (в данном файле пока не используется напрямую,
// но оставлен для возможных расширений и совместимости)
use cot\users\UsersRepository;

// Стандартная защита от прямого вызова файла
defined('COT_CODE') or die('Wrong URL');

// Подключаем общие функции форм (cot_inputbox, cot_shield_protect и др.)
require_once cot_incfile('forms');

// Получаем ID товара из GET-запроса (целое число), может использоваться при клонировании
$id = cot_import('id', 'G', 'INT');

// Получаем код категории из GET и сразу приводим к строке,
// чтобы избежать null в ключах массива структуры категорий
$c = (string) cot_import('c', 'G', 'TXT');

// Если категория пустая или не существует в структуре Market, сбрасываем в пустую строку
if ($c === '' || !isset(Cot::$structure['market'][$c])) {
    $c = '';
}

// Определяем действие $a из Request (GET+POST). 'ALP' — только буквенные символы.
$a = cot_import('a', 'R', 'ALP');

// Получаем права пользователя для модуля Market в целом (область 'any')
list(Cot::$usr['auth_read'], Cot::$usr['auth_write'], Cot::$usr['isadmin']) = cot_auth('market', 'any');

// Вызываем хук market.add.first — ранний хук, позволяющий плагинам вмешаться до основных действий
/* === Hook === */
foreach (cot_getextplugins('market.add.first') as $pl) {
    include $pl;
}
/* ===== */

// Блокируем доступ, если у пользователя нет права на запись в модуль Market
cot_block(Cot::$usr['auth_write']);

// Устанавливаем парсер по умолчанию из конфигурации модуля (будет использован для текста товара)
Cot::$sys['marketparser'] = Cot::$cfg['market']['marketparser'];

// Получаем список всех доступных парсеров (например, HTML, BBCode, Plain)
$parser_list = cot_get_parsers();

/* =====================================================================
 * ОБРАБОТКА ОТПРАВКИ ФОРМЫ ДОБАВЛЕНИЯ ТОВАРА
 * ---------------------------------------------------------------------
 * Блок выполняется, если в запросе присутствует действие $a == 'add'
 * (отправка формы создания нового товара). Здесь выполняются:
 *   - защита от CSRF;
 *   - импорт данных из POST;
 *   - обработка кнопки «Предпросмотр» (сохранение как черновик);
 *   - проверка прав на выбранную категорию;
 *   - валидация данных;
 *   - добавление товара в БД;
 *   - редирект в зависимости от итогового статуса товара;
 *   - при ошибках — возврат на форму.
 * ===================================================================== */
if ($a == 'add') {

    // Защита от CSRF-атак: проверяем токен формы (скрытое поле в форме отправки)
    cot_shield_protect();

    // Хук market.add.add.first — вызывается до импорта данных из POST.
    // Позволяет плагинам выполнить действия перед загрузкой данных формы.
    /* === Hook === */
    foreach (cot_getextplugins('market.add.add.first') as $pl) {
        include $pl;
    }
    /* ===== */

    // Импортируем данные товара из POST-запроса.
    // Параметры:
    //   'POST'            — источник данных;
    //   []                — пустой массив исходных данных (товар создаётся с нуля);
    //   Cot::$usr         — массив прав пользователя.
    // Функция возвращает массив $ritem с полями fieldmrkt_*.
    $ritem = cot_market_import('POST', [], Cot::$usr);

    /**
     * Обработка нажатия кнопки «Предпросмотр».
     *
     * Если в форме была нажата кнопка с именем "preview" (значение 1),
     * сохраняем товар как черновик (state = 2) и переходим на страницу предпросмотра.
     */
    if (cot_import('preview', 'P', 'BOL')) {

        // Принудительно устанавливаем статус "черновик" для сохраняемого товара.
        // Это нужно, чтобы предпросмотр не публиковал товар сразу.
        $ritem['fieldmrkt_state'] = MarketDictionary::STATE_DRAFT;

        // Если ошибок валидации нет (проверка на всякий случай)
        if (!cot_error_found()) {

            // Добавляем товар в БД и получаем его ID.
            // cot_market_add() принимает массив $ritem по ссылке и опционально массив прав.
            // Если права не переданы — функция сама подтянет их через cot_market_auth().
            $id = cot_market_add($ritem);

            // Если добавление прошло успешно (получен ID)
            if ($id) {
                // Перенаправляем пользователя на страницу предпросмотра товара
                cot_redirect(cot_url('market', ['m' => 'preview', 'id' => $id], '', true));
                // Завершаем скрипт, чтобы дальше код не выполнялся
                exit;
            }
        }
    }

    // После импорта данных из POST, у нас есть код категории из формы ($ritem['fieldmrkt_cat']).
    // Переопределяем права пользователя для этой конкретной категории.
    // Это важно, потому что пользователь мог выбрать категорию, отличную от начальной.
    list(Cot::$usr['auth_read'], Cot::$usr['auth_write'], Cot::$usr['isadmin']) = cot_auth('market', $ritem['fieldmrkt_cat']);

    // Блокируем доступ, если у пользователя нет права на запись в выбранной категории.
    // Такая ситуация возможна, если пользователь подменил поле категории в форме.
    cot_block(Cot::$usr['auth_write']);

    // Хук market.add.add.import — вызывается после импорта данных и повторной
    // проверки прав, но до валидации. Позволяет плагинам модифицировать данные.
    /* === Hook === */
    foreach (cot_getextplugins('market.add.add.import') as $pl) {
        include $pl;
    }
    /* ===== */

    // Валидируем данные товара: проверка обязательных полей, длины, формата и т.п.
    // Результат: если есть ошибки — они накапливаются через cot_error().
    cot_market_validate($ritem);

    // Хук market.add.add.error — вызывается после валидации.
    // Позволяет плагинам добавить свои проверки или изменить поведение
    // в зависимости от найденных ошибок.
    /* === Hook === */
    foreach (cot_getextplugins('market.add.add.error') as $pl) {
        include $pl;
    }
    /* ===== */

    // Если ошибок валидации нет
    if (!cot_error_found()) {

        // Добавляем товар в БД, передавая также массив прав текущего пользователя.
        // cot_market_add() сохраняет данные и возвращает ID нового товара
        // (или false/NULL в случае ошибки).
        $id = cot_market_add($ritem, Cot::$usr);

        // Проверяем, что товар успешно добавлен. Если ID не получен — значит,
        // сохранение не удалось (например, ошибка БД). В этом случае прерываем
        // выполнение с ошибкой, чтобы не сформировать некорректный URL для редиректа.
        if (empty($id)) {
            cot_error('Ошибка при добавлении товара в базу данных');
            cot_die_message(500);
        }

        // В зависимости от итогового статуса товара формируем URL для редиректа.
        switch ($ritem['fieldmrkt_state']) {

            // Статус 0: товар опубликован (STATE_PUBLISHED).
            case 0:
                // Если у товара есть алиас — ведём на ЧПУ-ссылку, иначе — по ID.
                $r_url = empty($ritem['fieldmrkt_alias'])
                    ? cot_url('market', ['c' => $ritem['fieldmrkt_cat'], 'id' => $id], '', true)
                    : cot_url('market', ['c' => $ritem['fieldmrkt_cat'], 'al' => $ritem['fieldmrkt_alias']], '', true);
                break;

            // Статус 1: товар отправлен на модерацию (STATE_PENDING).
            case 1:
                // Показываем пользователю стандартное сообщение о постановке в очередь.
                $r_url = cot_url('message', 'msg=300', '', true);
                break;

            // Статус 2: товар сохранён как черновик (STATE_DRAFT).
            case 2:
                // Выводим сообщение о сохранении в черновиках.
                cot_message('market_savedasdraft');
                // Перенаправляем пользователя на страницу редактирования товара,
                // чтобы он мог продолжить работу над черновиком.
                $r_url = cot_url('market', 'm=edit&id=' . $id, '', true);
                break;

            // Непредвиденный статус — на всякий случай ведём на страницу редактирования,
            // чтобы пользователь мог увидеть и исправить товар.
            default:
                cot_message('market_savedasdraft');
                $r_url = cot_url('market', 'm=edit&id=' . $id, '', true);
                break;
        }

        // Выполняем редирект на сформированный URL
        cot_redirect($r_url);

    } else {
        // Ветка с ошибками валидации: возвращаем пользователя обратно на форму.

        // Базовый набор параметров URL: действие 'add' (страница формы добавления)
        $urlParams = ['m' => 'add'];

        // Проверяем $c на непустую строку (переменная уже строка, поэтому empty() не нужен).
        // Если категория была задана — сохраняем её в URL, чтобы форма открылась в нужной категории.
        if ($c !== '') {
            $urlParams['c'] = $c;
        }

        // Перенаправляем пользователя на форму добавления с сохранением категории.
        // Сообщения об ошибках будут показаны после редиректа (они хранятся в сессии).
        cot_redirect(cot_url('market', $urlParams, '', true));
    }

}
/* =====================================================================
 * ИНИЦИАЛИЗАЦИЯ ЗНАЧЕНИЙ ПО УМОЛЧАНИЮ ДЛЯ ФОРМЫ ДОБАВЛЕНИЯ
 * ---------------------------------------------------------------------
 * Формируем массив $ritem со значениями по умолчанию для полей формы.
 * Эти значения используются, если пользователь открыл пустую форму
 * добавления товара (без клонирования). Для каждого поля задаётся
 * типовая «пустая» величина — строка или число.
 * ===================================================================== */

// Инициализируем массив данных товара значениями по умолчанию
$ritem = [
    // Meta-заголовок (пустая строка)
    'fieldmrkt_metatitle' => '',
    // SEO H1 (пустая строка)
    'fieldmrkt_metah1'    => '',
    // Meta-описание (пустая строка)
    'fieldmrkt_metadesc'  => '',
    // Алиас (пустая строка)
    'fieldmrkt_alias'     => '',
    // Название товара (пустая строка)
    'fieldmrkt_title'     => '',
    // Краткое описание (пустая строка)
    'fieldmrkt_desc'      => '',
    // Полный текст (пустая строка)
    'fieldmrkt_text'      => '',
    // Артикул (пустая строка)
    'fieldmrkt_pcod'      => '',
    // Цена по умолчанию (0.00)
    'fieldmrkt_costdflt'  => 0.00,
    // Цена в USD (0.00)
    'fieldmrkt_cost_usd'  => 0.00,
];

/* =====================================================================
 * ПОДДЕРЖКА КЛОНИРОВАНИЯ ТОВАРА
 * ---------------------------------------------------------------------
 * Если в GET-параметре передан clone=<ID>, загружаем данные
 * существующего товара из БД и используем их как основу для формы.
 * Это позволяет быстро создать новый товар на базе старого.
 * ===================================================================== */

// Импортируем параметр clone (целое число) из GET-запроса
$clone = cot_import('clone', 'G', 'INT');

// Если указан положительный ID для клонирования
if ($clone > 0) {

    // Загружаем данные товара по ID из таблицы market
    $ritem = Cot::$db->query('SELECT * FROM ' . Cot::$db->market . ' WHERE fieldmrkt_id = ?', $clone)->fetch();

    // Если товар с таким ID не найден — отдаём ошибку 404
    if (!$ritem) {
        cot_die_message(404);
    }
}

/* =====================================================================
 * ПРИСВОЕНИЕ КАТЕГОРИИ, ЕСЛИ ОНА НЕ ЗАДАНА
 * ---------------------------------------------------------------------
 * Если в массиве $ritem не заполнена категория (при обычном открытии
 * формы), подставляем значение из GET-параметра $c, если оно непустое.
 * ===================================================================== */

// Проверяем, пуста ли категория в массиве товара
if (empty($ritem['fieldmrkt_cat'])) {
    // Подставляем категорию из GET-параметра $c (или пустую строку)
    $ritem['fieldmrkt_cat'] = $c !== '' ? $c : '';
}

/* =====================================================================
 * ВЫБОР И ЗАГРУЗКА ШАБЛОНА
 * ---------------------------------------------------------------------
 * Определяем, какой шаблон использовать для формы добавления:
 *   - общий market.add.tpl;
 *   - либо специфичный для категории market.add.<tpl_категории>.tpl.
 * Если для категории задан параметр 'tpl', он добавляется в имя шаблона.
 * ===================================================================== */

// Код модуля, используется как первая часть имени файла шаблона
$tpl_ExtCode = 'market';

// Часть имени, обозначающая действие (добавление)
$tpl_PartExt = 'add';

// Инициализируем переменную специфичного шаблона категории пустой строкой
$tpl_PartExtSecond = '';

// Если категория задана и для неё определён отдельный шаблон (поле tpl)
if (!empty($ritem['fieldmrkt_cat']) && isset(Cot::$structure['market'][$ritem['fieldmrkt_cat']]['tpl'])) {
    // Используем специфичный шаблон для этой категории
    $tpl_PartExtSecond = Cot::$structure['market'][$ritem['fieldmrkt_cat']]['tpl'];
}

// Загружаем файл шаблона с учётом возможного специфичного шаблона категории
$extTplFile = cot_tplfile(
    [                         // Массив частей имени шаблона
        $tpl_ExtCode,         // 'market'
        $tpl_PartExt,         // 'add'
        $tpl_PartExtSecond    // например, 'my_category_tpl' или ''
    ],
    'module',                 // Область поиска (модуль)
    true                      // Вернуть полный путь к файлу
);

// Если файл шаблона не найден — регистрируем ошибку и прерываем выполнение
// с кодом 500 (без шаблона дальнейшая работа невозможна).
if (empty($extTplFile)) {
    cot_error('Шаблон не найден');
    cot_die_message(500);
}

// Формируем абсолютный путь к шаблону (для отладочного вывода в шаблоне)
$tpl_Path = Cot::$sys['abs_url'] . $extTplFile;

/* =====================================================================
 * ИНИЦИАЛИЗАЦИЯ МАССИВОВ ДЛЯ ХЛЕБНЫХ КРОШЕК И URL-ПАРАМЕТРОВ
 * ---------------------------------------------------------------------
 * Обе переменные наполняются ниже в блоке проверки прав.
 * ===================================================================== */

// Инициализируем массив для хлебных крошек
$breadcrumbs = [];
// Формируем базовые параметры URL для формы добавления
$urlParams = ['m' => 'add'];

/* =====================================================================
 * ПРОВЕРКА ПРАВ И ФОРМИРОВАНИЕ ПУТИ ДЛЯ КАТЕГОРИИ
 * ---------------------------------------------------------------------
 * Если категория задана — проверяем права пользователя на неё,
 * строим хлебные крошки, устанавливаем подраздел и URL-параметр c.
 * Если категория не задана — проверяем, есть ли у пользователя хотя бы
 * одна категория с правом записи, иначе блокируем.
 * ===================================================================== */

if (!empty($ritem['fieldmrkt_cat'])) {

    // Получаем права пользователя для конкретной категории товара
    list(Cot::$usr['auth_read'], Cot::$usr['auth_write'], Cot::$usr['isadmin']) = cot_auth('market', $ritem['fieldmrkt_cat']);

    // Блокируем доступ, если у пользователя нет права на запись в эту категорию
    cot_block(Cot::$usr['auth_write']);

    // Если категория заблокирована и пользователь не админ — отказ (сообщение 602)
    if (!Cot::$usr['isadmin'] && Cot::$structure['market'][$ritem['fieldmrkt_cat']]['locked']) {
        cot_die_message(602, TRUE);
    }

    // Устанавливаем подраздел (используется в заголовке/навигации)
    Cot::$sys['sublocation'] = Cot::$structure['market'][$ritem['fieldmrkt_cat']]['title'];

    // Строим цепочку хлебных крошек для категории
    $breadcrumbs = cot_structure_buildpath('market', $ritem['fieldmrkt_cat']);

    // Добавляем категорию в URL-параметры формы
    $urlParams['c'] = $ritem['fieldmrkt_cat'];

} else {

    // Категория не задана — пользователь открыл общую форму добавления

    // Для обычных пользователей проверяем наличие доступных категорий
    if (!Cot::$usr['isadmin']) {

        // Массив доступных для записи категорий
        $categories = [];

        // Если структура категорий не пуста
        if (!empty(Cot::$structure['market'])) {

            // Перебираем все категории модуля market
            foreach (Cot::$structure['market'] as $i => $x) {

                // Проверяем право на запись в текущую категорию
                $display = cot_auth('market', $i, 'W');

                // Если указана родительская категория $c, дополнительно проверяем,
                // что текущая категория является её подкатегорией или равна ей
                if ($display && $c !== '' && isset(Cot::$structure['market'][$c])) {
                    $mtch = Cot::$structure['market'][$c]['path'] . ".";
                    $mtchlen = mb_strlen($mtch);
                    $display = (mb_substr($x['path'], 0, $mtchlen) == $mtch || $i === $c);
                }

                // Если категория доступна и это не служебная 'all' — добавляем в массив
                if ($i != 'all' && $display) {
                    $categories[] = $i;
                }
            }
        }

        // Если ни одной доступной категории нет — блокируем доступ
        cot_block(count($categories) > 0);
    }

    // Устанавливаем общий заголовок подраздела для формы без категории
    Cot::$sys['sublocation'] = Cot::$L['market_form_add_item_title'];
}

/* =====================================================================
 * УСТАНОВКА ПОДЗАГОЛОВКА СТРАНИЦЫ И МЕТА-ТЕГА NOINDEX
 * ===================================================================== */

// Устанавливаем подзаголовок страницы (выводится в <title>)
Cot::$out['subtitle'] = Cot::$L['market_form_add_item_title'];

// Инициализируем массив head, если он ещё не задан
if (!isset(Cot::$out['head'])) {
    Cot::$out['head'] = '';
}
// Добавляем мета-тег noindex (страница не должна индексироваться поисковиками)
Cot::$out['head'] .= Cot::$R['code_noindex'];

// Добавляем последний элемент в хлебные крошки — саму страницу добавления
$breadcrumbs[] = [cot_url('market', $urlParams), Cot::$L['market_form_add_item_title']];

// Хук market.add.main — вызывается после подготовки всех основных данных,
// но до создания объекта XTemplate. Позволяет плагинам модифицировать
// переменные ($extTplFile, $breadcrumbs, $urlParams, $itemadd_array и др.)
// или выполнить свои действия перед финальным рендерингом.
/* === Hook === */
foreach (cot_getextplugins('market.add.main') as $pl) {
    include $pl;
}
/* ===== */

/* 
// ============================================
// Создаём объект шаблона с загруженным файлом
// --------------------------------------------
Объект шаблона $t = new XTemplate($extTplFile); создаётся после хука market.add.main, потому что:
Хук market.add.main предназначен для плагинов, которые могут изменять или дополнять данные перед окончательным рендерингом. 
Плагины могут:
	- изменить переменную $extTplFile (выбрать другой шаблон);
	- модифицировать массивы ($itemadd_array, $breadcrumbs, $urlParams);
	- добавить свои переменные для шаблона.
Создание объекта XTemplate до хука означало бы, что плагины уже не смогут повлиять на выбор файла шаблона или подготовку данных до инициализации шаблонизатора.
Такой порядок обеспечивает гибкость: сначала завершается вся логика и все хуки, затем создаётся объект шаблона с окончательными данными и производится вывод. Это стандартный паттерн (подход или структура кода) в Cotonti.
Проще говоря, это типичная последовательность действий, принятая в этой системе:
Сначала выполняется вся бизнес-логика (проверки, обработка данных, хуки).
И только после этого создаётся объект шаблонизатора (XTemplate) и происходит вывод.
Такой порядок не случаен — он позволяет плагинам через хуки влиять на данные или даже сам выбор шаблона до момента его инициализации. Это как «правило хорошего тона» в архитектуре Cotonti, которое упрощает поддержку и расширение кода.
 */

// Создаём объект шаблона на основе загруженного файла (после хука market.add.main)
$t = new XTemplate($extTplFile);
// Добавление товара
$itemadd_array = [
    // Заголовки и хлебные крошки
    'MARKETADD_BREADCRUMBS' => cot_breadcrumbs($breadcrumbs, Cot::$cfg['homebreadcrumb']),
	// сэндер
    'MARKETADD_FORM_SEND' => cot_url('market', 'm=add&a=add&c=' . $c),

    // Категории
    'MARKETADD_FORM_CAT' => cot_selectbox_structure('market', $ritem['fieldmrkt_cat'], 'ritemmarketcat'),
    'MARKETADD_FORM_CAT_SHORT' => cot_selectbox_structure('market', $ritem['fieldmrkt_cat'], 'ritemmarketcat', $c),
    'MARKETADD_FORM_CAT_S2' => cot_market_selectbox_structure_select2('market', $ritem['fieldmrkt_cat'], 'ritemmarketcat'),
    'MARKETADD_FORM_CAT_SHORT_S2' => cot_market_selectbox_structure_select2('market', $ritem['fieldmrkt_cat'], 'ritemmarketcat', $c),

    // SEO-поля
    'MARKETADD_FORM_META_TITLE' => cot_inputbox('text', 'ritemmarketmetatitle', $ritem['fieldmrkt_metatitle'], ['maxlength' => '255']),
    'MARKETADD_FORM_META_DESC' => cot_textarea('ritemmarketmetadesc', $ritem['fieldmrkt_metadesc'], 2, 64, ['maxlength' => '255']),
	'MARKETADD_FORM_META_H1'  => cot_inputbox('text', 'ritemmarketmetah1', $ritem['fieldmrkt_metah1'], ['maxlength' => '255']),

    // Основные поля
    'MARKETADD_FORM_ALIAS' => cot_inputbox('text', 'ritemmarketalias', $ritem['fieldmrkt_alias'], ['maxlength' => '255']),
	'MARKETADD_FORM_TITLE' => cot_inputbox('text', 'ritemmarkettitle', $ritem['fieldmrkt_title'], ['maxlength' => '255']),
    'MARKETADD_FORM_PCOD' => cot_inputbox('text', 'ritemmarketpcod', $ritem['fieldmrkt_pcod'], ['maxlength' => '64']),
    'MARKETADD_FORM_DESCRIPTION' => cot_textarea('ritemmarketdesc', $ritem['fieldmrkt_desc'], 2, 64, ['maxlength' => '255']),

    // Контент
    'MARKETADD_FORM_TEXT' => cot_textarea('ritemmarkettext', $ritem['fieldmrkt_text'], 24, 120, '', 'input_textarea_editor'),
    'MARKETADD_FORM_PARSER' => cot_selectbox(Cot::$cfg['market']['marketparser'], 'ritemmarketparser', $parser_list, $parser_list, false),

    // Цены
    'MARKETADD_FORM_COSTDFLT' => cot_inputbox('text', 'ritemmarketcostdflt', $ritem['fieldmrkt_costdflt'], 'size="10"'),
    'MARKETADD_FORM_COST_USD' => cot_inputbox('text', 'ritemmarketcostusd', $ritem['fieldmrkt_cost_usd'], 'size="10"'),
	
    // Владелец и дата
    'MARKETADD_FORM_OWNER' => cot_build_user(Cot::$usr['id'], Cot::$usr['name']),
    'MARKETADD_FORM_OWNER_ID' => Cot::$usr['id'],
    'MARKETADD_FORM_DATE' => cot_selectbox_date(Cot::$sys['now'], 'long', 'ritemmarketdate'),
];

$t->assign($itemadd_array);

/* =====================================================================
 * ОБРАБОТКА ДОПОЛНИТЕЛЬНЫХ ПОЛЕЙ (EXTRAFIELDS)
 * ---------------------------------------------------------------------
 * Если для таблицы cot_market зарегистрированы дополнительные поля,
 * выводим их в форму добавления товара. Каждое поле генерируется
 * с помощью API extrafields Cotonti и выводится в отдельный блок
 * MAIN.EXTRAFLD шаблона market.add.tpl.
 *
 * Флаг MARKETADD_HAS_EXTRAFIELDS позволяет в шаблоне условно показать
 * сообщение о наличии или отсутствии дополнительных полей.
 * ===================================================================== */

// Передаём в шаблон флаг: true, если есть хотя бы одно дополнительное поле.
// Используется в шаблоне для условного вывода блока с сообщением о полях.
$t->assign('MARKETADD_HAS_EXTRAFIELDS', !empty(Cot::$extrafields[Cot::$db->market]));

// Если для таблицы market зарегистрированы дополнительные поля
if (!empty(Cot::$extrafields[Cot::$db->market])) {

    // Перебираем все дополнительные поля, зарегистрированные для таблицы market
    foreach (Cot::$extrafields[Cot::$db->market] as $exfld) {

        // Формируем имя тега в верхнем регистре (например, fieldmrkt_status -> STATUS)
        // Используется для построения имени тега вида MARKETADD_FORM_STATUS
        $uname = strtoupper($exfld['field_name']);

        // Определяем значение поля:
        //   - если в массиве $ritem уже есть значение (например, при клонировании) — берём его;
        //   - иначе null, чтобы не было warning.
        // Ключ в массиве $ritem всегда с префиксом 'fieldmrkt_'.
        $data = isset($ritem['fieldmrkt_' . $exfld['field_name']])
            ? $ritem['fieldmrkt_' . $exfld['field_name']]
            : null;

        // Генерируем HTML-элемент поля через API extrafields.
        // Параметры:
        //   'ritemmarket' . $exfld['field_name'] — имя поля в форме (с префиксом);
        //   $exfld — описание поля из extrafields;
        //   $data — текущее значение (или null).
        $exfld_val = cot_build_extrafields('ritemmarket' . $exfld['field_name'], $exfld, $data);

        // Получаем заголовок поля (локализованное название) с префиксом 'market_'
        $exfld_title = cot_extrafield_title($exfld, 'market_');

        // Передаём в шаблон набор тегов для текущего дополнительного поля.
        // Используются две группы тегов:
        //   1. Уникальные теги с именем поля: MARKETADD_FORM_<ИМЯ> и _TITLE
        //      (для прямого вывода конкретного поля в шаблоне).
        //   2. Общие теги внутри цикла EXTRAFLD: MARKETADD_FORM_EXTRAFLD и _TITLE
        //      (для автоматического перебора всех полей в шаблоне).
        $t->assign([
            // Готовый HTML-элемент поля
            'MARKETADD_FORM_' . $uname => $exfld_val,

            // Локализованный заголовок поля
            'MARKETADD_FORM_' . $uname . '_TITLE' => $exfld_title,

            // Универсальные теги для вывода внутри цикла <!-- BEGIN: EXTRAFLD -->
            'MARKETADD_FORM_EXTRAFLD' => $exfld_val,
            'MARKETADD_FORM_EXTRAFLD_TITLE' => $exfld_title,

            // Машинное имя поля (например, 'product_status') — для отладки и т.п.
            'MARKETADD_FORM_EXTRAFLD_CODENAME' => $exfld['field_name'],
        ]);

        // Парсим блок MAIN.EXTRAFLD шаблона.
        // При каждой итерации цикла создаётся новый экземпляр блока,
        // который затем выводится в месте, где объявлен <!-- BEGIN: EXTRAFLD --> ... <!-- END: EXTRAFLD -->.
        $t->parse('MAIN.EXTRAFLD');
    }
}
// в шаблоне показываем путь к нему
$t->assign('TPL_PATH', $tpl_Path);

// Error and message handling
cot_display_messages($t);

