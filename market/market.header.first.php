/**
 * Проверяем, что константа COT_CODE определена — стандартная защита от прямого вызова файла.
 * Если скрипт запущен не в составе Cotonti, die прерывает выполнение с сообщением об ошибке.
 */
defined('COT_CODE') or die('Wrong URL.');

/**
 * Если текущее расширение (модуль) не является 'market', то наш хук не должен выполняться.
 * Таким образом, все последующие проверки и подмены заголовка работают только для страниц модуля маркета.
 */
if (Cot::$env['ext'] !== 'market') return;

/**
 * Подключаем главный файл модуля market, чтобы получить доступ к его функциям, в том числе
 * к тем, которые мы добавили для проверки существования шаблонов заголовков (market_cat_has_header_tpl и др.).
 */
require_once cot_incfile('market', 'module');

// Дефолтная локация для корня модуля (header.market.tpl)
Cot::$env['location'] = 'market';

/* была проблема по header.market.tpl
не было установки локации по умолчанию для главной страницы модуля. 
Сейчас блоки условий срабатывают только при наличии id, al или сегментов, 
но когда мы заходим на корень модуля (например, /ru/market), ни одно из этих условий не выполняется — Cot::$env['location'] остаётся пустым. 
В результате system/header.php получает ['header', ''] и не находит шаблон header.market.tpl. */

// 1. ID-товара (числовой)
/**
 * Проверяем, передан ли в GET-запросе параметр 'id'. Если он присутствует и не пуст,
 * значит пользователь просматривает конкретный товар по его числовому идентификатору.
 */
if (!empty($_GET['id'])) {
    /**
     * Приводим значение параметра 'id' к целому числу, чтобы избежать SQL-инъекций.
     * Если после приведения получился 0, значит параметр был некорректным — игнорируем.
     */
    $id = (int)$_GET['id'];
    if ($id > 0) {
        /**
         * Выполняем запрос к таблице маркета для получения кода категории (fieldmrkt_cat) товара по его ID.
         * Используем подготовленный запрос с плейсхолдером ? для безопасной подстановки значения.
         * fetchColumn() возвращает значение первого столбца первой строки результата.
         */
        $cat = Cot::$db->query(
            "SELECT fieldmrkt_cat FROM " . Cot::$db->market . " WHERE fieldmrkt_id = ? LIMIT 1",
            [$id]
        )->fetchColumn();
        /**
         * Если запрос вернул не пустое значение категории, продолжаем проверку шаблонов.
         * Если код категории пуст или не найден, переходим к следующим способам определения.
         */
        if ($cat) {
            /**
             * Сначала ищем специализированный шаблон для страницы товара с суффиксом '.pagehasid'.
             * Функция market_cat_has_header_tpl_pageid проверяет существование файла header.market.{cat}.pagehasid.tpl.
             */
            if (market_cat_has_header_tpl_pageid($cat)) {
                /**
                 * Если такой шаблон существует, подменяем переменную location на 'market.{cat}.pagehasid'.
                 * Это заставит Cotonti искать шаблон заголовка с соответствующим именем.
                 */
                Cot::$env['location'] = 'market.' . $cat . '.pagehasid';
                /**
                 * Немедленно выходим из хука, так как нужный location уже установлен.
                 */
                return;
            }
            /**
             * Если специализированный шаблон для страницы товара не найден, проверяем общий шаблон категории.
             * Функция market_cat_has_header_tpl ищет файл header.market.{cat}.tpl.
             */
            if (market_cat_has_header_tpl($cat)) {
                /**
                 * Устанавливаем location в 'market.{cat}' для использования общего шаблона заголовка категории.
                 */
                Cot::$env['location'] = 'market.' . $cat;
                return;
            }
        }
    }
}

// 2. alias-товара (ЧПУ)
/**
 * В Cotonti при использовании ЧПУ товары могут открываться по параметру 'al' (алиас).
 * Проверяем, есть ли такой параметр в GET-запросе.
 */
if (!empty($_GET['al'])) {
    /**
     * Безопасно получаем значение алиаса через функцию cot_import, которая фильтрует входные данные.
     * Режим 'G' — GET, 'TXT' — текст.
     */
    $al = cot_import('al', 'G', 'TXT');
    /**
     * Если после фильтрации алиас не пустой, выполняем запрос к базе данных.
     */
    if ($al) {
        /**
         * Ищем категорию товара по его алиасу в таблице маркета.
         * Аналогично числовому ID, получаем код категории через fetchColumn().
         */
        $cat = Cot::$db->query(
            "SELECT fieldmrkt_cat FROM " . Cot::$db->market . " WHERE fieldmrkt_alias = ? LIMIT 1",
            [$al]
        )->fetchColumn();
        /**
         * Если категория найдена, пытаемся применить шаблоны.
         */
        if ($cat) {
            /**
             * Проверяем наличие шаблона страницы товара с .pagehasid для найденной категории.
             */
            if (market_cat_has_header_tpl_pageid($cat)) {
                /**
                 * Устанавливаем location для специализированного шаблона.
                 */
                Cot::$env['location'] = 'market.' . $cat . '.pagehasid';
                return;
            }
            /**
             * Если специальный шаблон отсутствует, проверяем общий шаблон категории.
             */
            if (market_cat_has_header_tpl($cat)) {
                /**
                 * Устанавливаем location для общего шаблона категории.
                 */
                Cot::$env['location'] = 'market.' . $cat;
                return;
            }
        }
    }
}

// 3. Списки категорий (URL-парсинг, только если нет товара)
// 3. Списки категорий (URL-сегменты) – обход с конца для приоритета дочерних категорий
if (empty($_GET['id']) && empty($_GET['al'])) {
    $uri = trim($_SERVER['REQUEST_URI'] ?? '', '/');
    $segments = explode('/', $uri);

    // Убираем языковой префикс, если есть
    if (isset($segments[0]) && strlen($segments[0]) == 2 && ctype_alpha($segments[0])) {
        array_shift($segments);
    }

    if (!empty($segments[0]) && $segments[0] === 'market') {
        // Обходим с конца, чтобы самая конкретная категория имела приоритет
        for ($i = count($segments) - 1; $i >= 1; $i--) {
            $possibleCat = $segments[$i];
            if (market_cat_has_header_tpl($possibleCat)) {
                Cot::$env['location'] = 'market.' . $possibleCat;
                return;
            }
        }
    }
}
// 4. Старый ?c=
/**
 * Для обратной совместимости поддерживаем старый способ указания категории через параметр 'c' в GET.
 */
if (!empty($_GET['c'])) {
    /**
     * Безопасно получаем значение 'c' с помощью cot_import.
     */
    $c = cot_import('c', 'G', 'TXT');
    /**
     * Если значение не пустое и для него есть шаблон заголовка, применяем его.
     */
    if ($c && market_cat_has_header_tpl($c)) {
        /**
         * Устанавливаем location для категории, переданной через параметр 'c'.
         */
        Cot::$env['location'] = 'market.' . $c;
    }
}

