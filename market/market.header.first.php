/**
 * Market PRO Module for CMF Cotonti, PHP v.8.5+, MySQL v.8.4
 *
 * Обработчик хука `header.first` для модуля Market.
 *
 * Назначение:
 *   Позволяет динамически задавать параметр `Cot::$env['location']` для страниц модуля Market,
 *   чтобы подключать специфические header-шаблоны (header.market.*.tpl) в зависимости от
 *   просматриваемого товара (по ID или алиасу) или категории (по URL-сегментам или параметру `c`).
 *
 * Что делает:
 *   1. Проверяет, что текущий модуль — market, иначе выходит.
 *   2. Устанавливает location по умолчанию для корня модуля (`market`).
 *   3. При наличии ID товара определяет его категорию и ищет соответствующие шаблоны:
 *      `header.market.{cat}.pagehasid.tpl` (специализированный для товара) или
 *      `header.market.{cat}.tpl` (общий для категории).
 *   4. При наличии алиаса (`al`) выполняет аналогичный поиск.
 *   5. Если нет ID/алиаса, анализирует URL-сегменты после `market/`, обходит их с конца,
 *      чтобы найти самую конкретную категорию с существующим шаблоном.
 *   6. Поддерживает устаревший способ указания категории через `?c=`.
 *
 * Почему нужен:
 *   Без этого файла страницы модуля Market не смогут использовать индивидуальные
 *   header-шаблоны для разных категорий и товаров, что важно для SEO и визуального оформления.
 *
 * Filename: market.header.first.php
 *
 * Path:    modules/market/market.header.first.php
 *
