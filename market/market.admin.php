/**
 * ============================================================
 * ДОКУМЕНТАЦИЯ ПО ХУКУ `admin` И ФАЙЛУ market.admin.php
 * ============================================================
 *
 * Хук `admin` в Cotonti используется для подключения административных
 * страниц модулей. Файл market.admin.php является точкой входа в
 * административную панель модуля Market PRO. Он вызывается при переходе
 * администратора в раздел управления товарами (обычно admin.php?m=market).
 *
 * Файл обрабатывает следующие действия:
 *   - просмотр списка товаров с возможностью фильтрации по статусу, категории;
 *   - поиск по названию, полному описанию или артикулу;
 *   - массовое утверждение (validate) и удаление (delete) выбранных товаров;
 *   - индивидуальное утверждение, снятие с публикации, удаление товара;
 *   - отображение общего количества товаров, ожидающих модерации;
 *   - ссылки на настройки модуля, структуру категорий, дополнительные поля.
 *
 * Все операции выполняются только после проверки прав администратора.
 *
 * Основные параметры URL:
 *   m=market        — указывает на этот файл (админ-раздел);
 *   a=<действие>    — validate, unvalidate, delete, update_checked;
 *   id=<id товара>  — используется при индивидуальных действиях;
 *   filter=<статус> — all, valqueue, validated, drafts, expired;
 *   sorttype, sortway — сортировка;
 *   sq=<запрос>     — поисковый запрос;
 *   search_in       — область поиска: title, full, pcod;
 *   c=<код категории> — фильтр по категории.
 *
 * Логика работы:
 *   1. Проверка прав администратора.
 *   2. Инициализация шаблона.
 *   3. Обработка действий (validate, unvalidate, delete, update_checked)
 *      с соответствующими проверками, транзакциями, очисткой кэша.
 *   4. Формирование списка товаров с учётом фильтров и пагинации.
 *   5. Вывод данных в шаблон, включая инструменты массовых операций.
 *
 * Используемые сервисы и классы:
 *   MarketDictionary       — константы статусов товара;
 *   MarketControlService   — сервис удаления товаров;
 *   Cot::$db               — прямое обращение к базе данных.
 *
 * Source and updates   https://github.com/webitproff/marketpro-cotonti
 * ReadMeMore:          https://abuyfile.com/ru/market/cotonti/plugs/marketpro
 * Support:             https://abuyfile.com/ru/forums/cotonti/custom/marketpro
 *
 * Date: Sep 10, 2026
 *
 * @package market
 * @version 5.7.9
 * @author webitproff
 * @copyright Copyright (c) webitproff 2026 | https://github.com/webitproff/marketpro-cotonti
 * @license BSD
 */
// Импортируем класс MarketDictionary для использования констант статусов товара
use cot\modules\market\inc\MarketDictionary;
// Импортируем сервис управления товарами (удаление и т.п.)
use cot\modules\market\inc\MarketControlService;

// Проверяем, что скрипт запущен в контексте админ-панели Cotonti (определены COT_CODE и COT_ADMIN)
(defined('COT_CODE') && defined('COT_ADMIN')) or die('Wrong URL.');

// Подключаем главный файл модуля Market (функции, языковые строки, настройки)
require_once cot_incfile('market', 'module');

// Получаем права текущего пользователя для модуля Market (область 'any' – без конкретной категории)
list(Cot::$usr['auth_read'], Cot::$usr['auth_write'], Cot::$usr['isadmin']) = cot_auth('market', 'any');

// Блокируем доступ, если пользователь не является администратором модуля Market
cot_block(Cot::$usr['isadmin']);

/* =====================================================================
 * ИНИЦИАЛИЗАЦИЯ ШАБЛОНА
 * ---------------------------------------------------------------------
 * Определяем имя части шаблона 'admin' и загружаем файл шаблона.
 * Если файл не найден, выводим ошибку.
 * ===================================================================== */

// Часть имени шаблона – 'admin'
$tpl_PartExt = 'admin';

// Получаем полный путь к файлу шаблона market.admin.tpl
$mskin = cot_tplfile(['market', $tpl_PartExt], 'module', true);

// Если шаблон не найден, регистрируем ошибку
if (empty($mskin)) cot_error('Шаблон не найден');

// Формируем абсолютный путь к шаблону для отладки (передаётся в шаблон)
$tpl_Path = $sys['abs_url'] . $mskin;

// Создаём объект XTemplate для работы с шаблоном
$t = new XTemplate($mskin);

/* =====================================================================
 * ФОРМИРОВАНИЕ ХЛЕБНЫХ КРОШЕК И ЗАГОЛОВКА АДМИН-ПАНЕЛИ
 * ===================================================================== */

// Первый элемент хлебных крошек – ссылка на раздел "Расширения"
$adminPath[] = [cot_url('admin', 'm=extensions'), Cot::$L['Extensions']];

// Второй элемент – название модуля (из массива $cot_modules)
$adminPath[] = [cot_url('admin', 'm=extensions&a=details&mod='.$m), $cot_modules[$m]['title']];

// Третий элемент – текущий раздел администрирования
$adminPath[] = [cot_url('admin', 'm='.$m), Cot::$L['Administration']];

// Текст справки для администратора (выводится в подсказке)
$adminHelp = Cot::$L['adm_lang_market_help_market'];

// Заголовок страницы админки
$adminTitle = Cot::$L['market_title_general'];

/* =====================================================================
 * ПОЛУЧЕНИЕ ПАРАМЕТРОВ ЗАПРОСА
 * ===================================================================== */

// Импортируем ID товара из GET (целое число)
$id = cot_import('id', 'G', 'INT');

// Импортируем код категории из GET (текст)
$c  = cot_import('c',  'G', 'TXT'); // выбранная категория из URL

// Импортируем поисковый запрос из GET (текст)
$sq = cot_import('sq', 'G', 'TXT');

// Если поисковый запрос не null, удаляем пробелы в начале и конце
$sq = ($sq !== null) ? trim($sq) : '';

// Импортируем действие из GET (только буквы)
$a = cot_import('a', 'G', 'ALP');

/* ---------------------------------------------------------------------
 * ОБЛАСТЬ ПОИСКА (search_in)
 * ---------------------------------------------------------------------
 * Параметр search_in определяет, где искать: в названии, в полном тексте
 * или в артикуле. Если значение недопустимо, по умолчанию 'title'.
 * --------------------------------------------------------------------- */

// Получаем область поиска, максимальная длина 8 символов
$search_in = cot_import('search_in', 'G', 'ALP', 8);

// Проверяем, что значение входит в допустимые варианты, иначе сбрасываем на 'title'
if (!in_array($search_in, ['title', 'full', 'pcod'])) {
    $search_in = 'title';
}

/* ---------------------------------------------------------------------
 * ПОДГОТОВКА СЛОВ ДЛЯ ПОДСВЕТКИ В РЕЗУЛЬТАТАХ ПОИСКА
 * ---------------------------------------------------------------------
 * Разбиваем поисковый запрос на отдельные слова для JavaScript-подсветки.
 * --------------------------------------------------------------------- */

// Инициализируем массив слов для подсветки
$highlight_words = array();

// Если поисковый запрос не пустой, разбиваем его на слова по пробелам
if (!empty($sq)) {
    $highlight_words = preg_split('/\s+/', $sq, -1, PREG_SPLIT_NO_EMPTY);
}

/* =====================================================================
 * ПАГИНАЦИЯ И СОРТИРОВКА
 * ===================================================================== */

// Получаем параметры пагинации (смещение $d, $durl для URL) из GET.
// Количество записей на страницу берём из настройки marketmaxlistsperpageadmin.
list($pg, $d, $durl) = cot_import_pagenav('d', Cot::$cfg['market']['marketmaxlistsperpageadmin']);

// Импортируем параметр сортировки (поле) из Request (GET+POST)
$sorttype = cot_import('sorttype', 'R', 'ALP');

// Если сортировка не задана, используем 'id'
$sorttype = empty($sorttype) ? 'id' : $sorttype;

// Проверяем, что поле сортировки существует в таблице market (кроме 'id').
// Если поля нет, сбрасываем на 'id'.
if ($sorttype != 'id' && !Cot::$db->fieldExists(Cot::$db->market, "fieldmrkt_$sorttype")) {
    $sorttype = 'id';
}

// Формируем имя SQL-поля с префиксом fieldmrkt_
$sqlsorttype = 'fieldmrkt_'.$sorttype;

// Получаем доступные поля для сортировки из конфигурации модуля
$sort_type = cot_market_config_order(true);

// Импортируем направление сортировки (asc/desc)
$sortway = cot_import('sortway', 'R', 'ALP');

// По умолчанию направление – 'desc'
$sortway = empty($sortway) ? 'desc' : $sortway;

// Массив доступных направлений с локализованными названиями
$sort_way = [
    'asc' => Cot::$L['Ascending'],
    'desc' => Cot::$L['Descending'],
];

// Устанавливаем SQL-направление сортировки
$sqlsortway = $sortway;

/* =====================================================================
 * ФИЛЬТР ПО СТАТУСУ
 * ===================================================================== */

// Импортируем фильтр статуса
$filter = cot_import('filter', 'R', 'ALP');

// Если фильтр не задан, используем 'all' (все товары)
$filter = empty($filter) ? 'all' : $filter;

// Массив доступных фильтров с локализованными названиями
$filter_type = [
    'all' => Cot::$L['All'],
    'valqueue' => Cot::$L['adm_lang_market_valqueue'],
    'validated' => Cot::$L['adm_lang_market_validated'],
    'expired' => Cot::$L['adm_lang_market_expired'],
    'drafts' => Cot::$L['market_drafts'],
];

/* =====================================================================
 * ФОРМИРОВАНИЕ URL ПАРАМЕТРОВ ДЛЯ ССЫЛОК
 * ===================================================================== */

// Базовый массив URL-параметров
$urlParams = ['m' => 'market'];

// Если сортировка отличается от 'id', добавляем её в URL
if ($sorttype != 'id') {
    $urlParams['sorttype'] = $sorttype;
}

// Если направление сортировки не 'desc', добавляем
if ($sortway != 'desc') {
    $urlParams['sortway'] = $sortway;
}

// Если фильтр не 'valqueue' (по умолчанию 'valqueue'?), добавляем.
// В текущем коде по умолчанию 'all', но условие оставлено от старой логики.
if ($filter != 'valqueue') {
    $urlParams['filter'] = $filter;
}

// Если есть поисковый запрос, добавляем
if (!empty($sq)) {
    $urlParams['sq'] = $sq;
}

// Если задана категория, добавляем
if (!empty($c)) {
    $urlParams['c'] = $c;
}

// Если область поиска не 'title', добавляем
if ($search_in != 'title') {
    $urlParams['search_in'] = $search_in;
}

/**
 * Common UrlParams without pagination
 * @deprecated
 * (Устаревшая строка, сохранена для обратной совместимости)
 */
$common_params = http_build_query($urlParams, '', '&');

// Если текущая страница > 1, добавляем параметр смещения в URL
if ($pg > 1) {
    $urlParams['d'] = $durl;
}

/* =====================================================================
 * ФОРМИРОВАНИЕ SQL-УСЛОВИЯ $sqlwhere
 * ===================================================================== */

// Блок формирования $sqlwhere в зависимости от выбранного фильтра.
// Базовое условие для всех: заголовок не NULL и не пустой.
if ($filter == 'all') {
    // Все товары
    $sqlwhere = "fieldmrkt_title IS NOT NULL AND fieldmrkt_title != ''";
} elseif ($filter == 'valqueue') {
    // Ожидают утверждения (STATE_PENDING)
    $sqlwhere = 'fieldmrkt_state = ' . MarketDictionary::STATE_PENDING . " AND fieldmrkt_title IS NOT NULL AND fieldmrkt_title != ''";
} elseif ($filter == 'validated') {
    // Опубликованные (STATE_PUBLISHED)
    $sqlwhere = 'fieldmrkt_state = ' . MarketDictionary::STATE_PUBLISHED . " AND fieldmrkt_title IS NOT NULL AND fieldmrkt_title != ''";
} elseif ($filter == 'drafts') {
    // Черновики (STATE_DRAFT)
    $sqlwhere = 'fieldmrkt_state = ' . MarketDictionary::STATE_DRAFT . " AND fieldmrkt_title IS NOT NULL AND fieldmrkt_title != ''";
} elseif ($filter == 'expired') {
    // Истёкшие (expire > 0 и меньше текущего времени)
    $sqlwhere = 'fieldmrkt_expire > 0 AND fieldmrkt_expire < ' . (int) Cot::$sys['now'] . " AND fieldmrkt_title IS NOT NULL AND fieldmrkt_title != ''";
} else {
    // На случай непредвиденных значений – все товары
    $sqlwhere = "fieldmrkt_title IS NOT NULL AND fieldmrkt_title != ''";
}

// Инициализируем массив параметров для подготовленных запросов
$params = []; // параметры для SQL

/* ---------------------------------------------------------------------
 * ПОИСКОВЫЙ ФИЛЬТР
 * ---------------------------------------------------------------------
 * В зависимости от области поиска добавляем условие LIKE.
 * --------------------------------------------------------------------- */

// Если поисковый запрос не пустой
if (!empty($sq)) {
    // Экранированный шаблон поиска: %$sq%
    $sq_escaped = "%$sq%";

    // Если ищем только в названии
    if ($search_in == 'title') {
        $sqlwhere .= " AND fieldmrkt_title LIKE :sq";
    }
    // Если ищем в названии и полном описании
    elseif ($search_in == 'full') {
        $sqlwhere .= " AND (fieldmrkt_title LIKE :sq OR fieldmrkt_text LIKE :sq)";
    }
    // Если ищем по артикулу
    elseif ($search_in == 'pcod') {
        $sqlwhere .= " AND fieldmrkt_pcod LIKE :sq";
    }

    // Добавляем параметр для подстановки в SQL
    $params['sq'] = $sq_escaped;
}

/* ---------------------------------------------------------------------
 * ФИЛЬТР ПО КАТЕГОРИИ (С УЧЁТОМ ПОДКАТЕГОРИЙ)
 * ---------------------------------------------------------------------
 * Если выбрана категория, получаем все её дочерние категории и добавляем
 * условие IN. Если категория не задана, то условие не добавляется.
 * --------------------------------------------------------------------- */

// Получаем массив кодов категорий: выбранная + все подкатегории
$catsub = cot_structure_children('market', !empty($c) ? $c : '');

// Если массив не пустой, добавляем условие IN
if (!empty($catsub)) {
    $sqlwhere .= " AND fieldmrkt_cat IN ('" . implode("','", $catsub) . "')";
}

/* ---------------------------------------------------------------------
 * ЗАГРУЗКА СТРУКТУРЫ КАТЕГОРИЙ
 * ---------------------------------------------------------------------
 * Убеждаемся, что структура категорий Market загружена как массив.
 * Если она пуста или не массив, инициализируем пустым массивом.
 * --------------------------------------------------------------------- */

// Приводим структуру категорий к массиву (на случай, если не загружена)
cot::$structure['market'] = (!empty(cot::$structure['market']) && is_array(cot::$structure['market'])) ?
    cot::$structure['market'] : [];

/* ---------------------------------------------------------------------
 * ОПРЕДЕЛЕНИЕ URL ДЛЯ ВОЗВРАТА (backUrl)
 * ---------------------------------------------------------------------
 * Если в GET передан параметр back (base64-кодированный URL), используем его,
 * иначе формируем URL для возврата на список товаров.
 * --------------------------------------------------------------------- */

// Импортируем параметр back (HTML-закодированная строка)
$backUrl = cot_import('back', 'G', 'HTM');

// Если backUrl не пустой, декодируем из base64, иначе строим URL на основе $urlParams
$backUrl = !empty($backUrl) ? base64_decode($backUrl) : cot_url('admin', $urlParams, '', true);

/* ---------------------------------------------------------------------
 * ХУК market.admin.first
 * ---------------------------------------------------------------------
 * Вызываем плагины до начала основных действий. Позволяет модифицировать
 * переменные или добавить свою логику.
 * --------------------------------------------------------------------- */
/* === Hook  === */
foreach (cot_getextplugins('market.admin.first') as $pl) {
    include $pl;
}
/* ===== */

/* =====================================================================
 * ОБРАБОТКА ДЕЙСТВИЯ 'validate'
 * ---------------------------------------------------------------------
 * Данный блок выполняется, когда администратор нажимает на ссылку
 * "Утвердить" для конкретного товара (a=validate&id=...).
 * ===================================================================== */
if ($a == 'validate') {
    /* -----------------------------------------------------------------
     * ПРОВЕРКА ТОКЕНА БЕЗОПАСНОСТИ (GET-запрос)
     * cot_check_xg() проверяет параметр x в GET-запросе, чтобы защититься
     * от CSRF-атак. Если токен неверный, выполнение будет остановлено.
     * ----------------------------------------------------------------- */
    cot_check_xg();

    /* === Hook === */
    /* -----------------------------------------------------------------
     * ХУК market.admin.validate
     * Вызывается перед выполнением утверждения товара.
     * Позволяет плагинам вмешаться в процесс.
     * ----------------------------------------------------------------- */
    foreach (cot_getextplugins('market.admin.validate') as $pl) {
        include $pl;
    }
    /* ===== */

    /* -----------------------------------------------------------------
     * ЗАПРОС ДАННЫХ ТОВАРА
     * Выбираем из БД поля: ID, алиас, категорию, текущее состояние товара.
     * Используется подготовленный запрос с плейсхолдером ? и параметром $id.
     * fetch() возвращает одну строку или false, если не найдено.
     * ----------------------------------------------------------------- */
    $row = Cot::$db->query(
        'SELECT fieldmrkt_id, fieldmrkt_alias, fieldmrkt_cat, fieldmrkt_state FROM ' . Cot::$db->market
        . ' WHERE fieldmrkt_id = ?',
        $id
    )->fetch();

    /* -----------------------------------------------------------------
     * ЕСЛИ ТОВАР НАЙДЕН
     * ----------------------------------------------------------------- */
    if ($row) {
        /* --------------------------------------------------------------
         * Проверяем, не опубликован ли уже товар.
         * Если текущее состояние равно STATE_PUBLISHED (0), значит товар
         * уже утверждён, и повторное утверждение не требуется.
         * Выводим сообщение и перенаправляем обратно.
         * -------------------------------------------------------------- */
        if ($row['fieldmrkt_state'] == MarketDictionary::STATE_PUBLISHED) {
            cot_message('#' . $id . ' - ' . Cot::$L['adm_lang_market_already_updated']);
            cot_redirect($backUrl);
        }

        /* --------------------------------------------------------------
         * ПРОВЕРКА ПРАВ НА КАТЕГОРИЮ
         * cot_auth('market', $row['fieldmrkt_cat'], 'A') проверяет,
         * имеет ли текущий администратор право администрирования 'A'
         * для конкретной категории товара. Если нет — cot_block() заблокирует.
         * -------------------------------------------------------------- */
        $usr['isadmin_local'] = cot_auth('market', $row['fieldmrkt_cat'], 'A');
        cot_block($usr['isadmin_local']);

        /* --------------------------------------------------------------
         * ФОРМИРУЕМ ДАННЫЕ ДЛЯ ОБНОВЛЕНИЯ
         * Устанавливаем новое состояние: STATE_PUBLISHED (опубликован).
         * -------------------------------------------------------------- */
        $data = ['fieldmrkt_state' => MarketDictionary::STATE_PUBLISHED];

        /* --------------------------------------------------------------
         * ОБНОВЛЯЕМ ТОВАР В БД
         * Используется Cot::$db->update(). Поле fieldmrkt_id = $id.
         * -------------------------------------------------------------- */
        $sql_market = Cot::$db->update(Cot::$db->market, $data, "fieldmrkt_id = $id");

        /* === Hook === */
        /* --------------------------------------------------------------
         * ХУК market.admin.validate.done
         * Вызывается после успешного обновления. Плагины могут выполнить
         * дополнительные действия (например, уведомления).
         * -------------------------------------------------------------- */
        foreach (cot_getextplugins('market.admin.validate.done') as $pl) {
            include $pl;
        }
        /* ===== */

        /* --------------------------------------------------------------
         * ЗАПИСЬ В ЖУРНАЛ ДЕЙСТВИЙ
         * cot_log() сохраняет событие в системный журнал Cotonti.
         * Параметры: текст сообщения, модуль 'market', действие 'validate',
         * результат 'done'.
         * -------------------------------------------------------------- */
        cot_log(
            Cot::$L['Market'] . ' #' . $id . ' - ' . Cot::$L['adm_lang_market_queue_validated'],
            'market',
            'validate',
            'done'
        );

        /* --------------------------------------------------------------
         * ОЧИСТКА КЭША
         * Если кэш включён, удаляем закэшированные данные:
         *   - структуру категорий;
         *   - страницу товара и категории (если включён кэш market);
         *   - главную страницу (если включён кэш index).
         * -------------------------------------------------------------- */
        if (Cot::$cache) {
            // Удаляем кэш структуры
            Cot::$cache->db->remove('structure', 'system');
            // Если кэш модуля Market включён
            if (Cot::$cfg['cache_market']) {
                // Очищаем кэш страницы товара
                Cot::$cache->static->clearByUri(cot_market_url($row));
                // Очищаем кэш страницы категории
                Cot::$cache->static->clearByUri(cot_url('market', ['c' => $row['fieldmrkt_cat']]));
            }
            // Если кэш главной страницы включён
            if (Cot::$cfg['cache_index']) {
                Cot::$cache->static->clear('index');
            }
        }

        /* --------------------------------------------------------------
         * ВЫВОД СООБЩЕНИЯ ОБ УСПЕХЕ
         * cot_message() добавляет сообщение, которое будет показано после редиректа.
         * -------------------------------------------------------------- */
        cot_message('#' . $id . ' - ' . Cot::$L['adm_lang_market_queue_validated']);

    } else {
        /* --------------------------------------------------------------
         * ЕСЛИ ТОВАР НЕ НАЙДЕН
         * Выводим сообщение об ошибке (nf — not found).
         * -------------------------------------------------------------- */
        cot_error('#' . $id . ' - ' . Cot::$L['nf']);
    }

    /* -----------------------------------------------------------------
     * ПЕРЕНАПРАВЛЕНИЕ ОБРАТНО
     * После выполнения действия перенаправляем пользователя на $backUrl.
     * ----------------------------------------------------------------- */
    cot_redirect($backUrl);

/* =====================================================================
 * ОБРАБОТКА ДЕЙСТВИЯ 'unvalidate'
 * ---------------------------------------------------------------------
 * Блок снятия товара с публикации (перевод в состояние "на модерации").
 * ===================================================================== */
} elseif ($a == 'unvalidate') {
    /* -----------------------------------------------------------------
     * ПРОВЕРКА ТОКЕНА БЕЗОПАСНОСТИ (GET)
     * ----------------------------------------------------------------- */
    cot_check_xg();

    /* === Hook === */
    /* -----------------------------------------------------------------
     * ХУК market.admin.unvalidate
     * ----------------------------------------------------------------- */
    foreach (cot_getextplugins('market.admin.unvalidate') as $pl) {
        include $pl;
    }
    /* ===== */

    /* -----------------------------------------------------------------
     * ЗАПРОС ДАННЫХ ТОВАРА (аналогично validate)
     * ----------------------------------------------------------------- */
    $row = Cot::$db->query(
        'SELECT fieldmrkt_id, fieldmrkt_alias, fieldmrkt_cat, fieldmrkt_state FROM ' . Cot::$db->market . ' WHERE fieldmrkt_id = ?',
        $id
    )->fetch();

    /* -----------------------------------------------------------------
     * ЕСЛИ ТОВАР НАЙДЕН
     * ----------------------------------------------------------------- */
    if ($row) {
        /* --------------------------------------------------------------
         * Проверяем, не находится ли товар уже в состоянии "на модерации"
         * (STATE_PENDING). Если да — выводим сообщение и перенаправляем.
         * -------------------------------------------------------------- */
        if ($row['fieldmrkt_state'] == MarketDictionary::STATE_PENDING) {
            cot_message('#' . $id . ' - ' . Cot::$L['adm_lang_market_already_updated']);
            cot_redirect($backUrl);
        }

        /* --------------------------------------------------------------
         * ПРОВЕРКА ПРАВ НА КАТЕГОРИЮ
         * -------------------------------------------------------------- */
        Cot::$usr['isadmin_local'] = cot_auth('market', $row['fieldmrkt_cat'], 'A');
        cot_block($usr['isadmin_local']);

        /* --------------------------------------------------------------
         * ОБНОВЛЕНИЕ СТАТУСА НА STATE_PENDING
         * -------------------------------------------------------------- */
        $sql_market = Cot::$db->update(
            Cot::$db->market,
            ['fieldmrkt_state' => MarketDictionary::STATE_PENDING],
            'fieldmrkt_id = ?',
            $id
        );

        /* --------------------------------------------------------------
         * ЗАПИСЬ В ЖУРНАЛ
         * -------------------------------------------------------------- */
        cot_log(Cot::$L['Market'] . ' #' . $id . ' - ' . Cot::$L['adm_lang_market_queue_unvalidated'], 'market', 'unvalidated', 'done');

        /* --------------------------------------------------------------
         * ОЧИСТКА КЭША (аналогично validate)
         * -------------------------------------------------------------- */
        if (Cot::$cache) {
            Cot::$cache->db->remove('structure', 'system');
            if (Cot::$cfg['cache_market']) {
                Cot::$cache->static->clearByUri(cot_market_url($row));
                Cot::$cache->static->clearByUri(cot_url('market', ['c' => $row['fieldmrkt_cat']]));
            }
            if (Cot::$cfg['cache_index']) {
                Cot::$cache->static->clear('index');
            }
        }

        /* --------------------------------------------------------------
         * СООБЩЕНИЕ ОБ УСПЕХЕ
         * -------------------------------------------------------------- */
        cot_message('#' . $id . ' - ' . Cot::$L['adm_lang_market_queue_unvalidated']);

    } else {
        /* --------------------------------------------------------------
         * ТОВАР НЕ НАЙДЕН — ОШИБКА
         * -------------------------------------------------------------- */
        cot_error('#' . $id . ' - ' . Cot::$L['nf']);
    }

    /* -----------------------------------------------------------------
     * РЕДИРЕКТ ОБРАТНО
     * ----------------------------------------------------------------- */
    cot_redirect($backUrl);

/* =====================================================================
 * ОБРАБОТКА ДЕЙСТВИЯ 'delete'
 * ---------------------------------------------------------------------
 * Блок удаления товара.
 * ===================================================================== */
} elseif ($a == 'delete') {
    /* -----------------------------------------------------------------
     * ПРОВЕРКА ТОКЕНА (GET)
     * ----------------------------------------------------------------- */
    cot_check_xg();

    /* === Hook === */
    /* -----------------------------------------------------------------
     * ХУК market.admin.delete
     * ----------------------------------------------------------------- */
    foreach (cot_getextplugins('market.admin.delete') as $pl) {
        include $pl;
    }
    /* ===== */

    /* -----------------------------------------------------------------
     * ВЫЗОВ СЕРВИСА УДАЛЕНИЯ
     * MarketControlService::getInstance()->delete($id) удаляет товар.
     * Возвращает сообщение об успехе (строка) или false при ошибке.
     * ----------------------------------------------------------------- */
    $resultOrMessage = MarketControlService::getInstance()->delete($id);

    /* -----------------------------------------------------------------
     * ПРОВЕРКА РЕЗУЛЬТАТА
     * ----------------------------------------------------------------- */
    if ($resultOrMessage !== false) {
        /* === Hook === */
        /* --------------------------------------------------------------
         * ХУК market.admin.delete.done
         * Вызывается после успешного удаления.
         * -------------------------------------------------------------- */
        foreach (cot_getextplugins('market.admin.delete.done') as $pl) {
            include $pl;
        }
        /* ===== */

        /* --------------------------------------------------------------
         * ВЫВОД СООБЩЕНИЯ ОБ УСПЕХЕ
         * -------------------------------------------------------------- */
        cot_message('#' . $id . ' - ' . $resultOrMessage);
    } else {
        /* --------------------------------------------------------------
         * ЕСЛИ ОШИБКА — СООБЩЕНИЕ ОБ ОШИБКЕ
         * -------------------------------------------------------------- */
        cot_error('#' . $id . ' - ' . Cot::$L['adm_lang_market_failed']);
    }

    /* -----------------------------------------------------------------
     * РЕДИРЕКТ НА СПИСОК ТОВАРОВ
     * ----------------------------------------------------------------- */
    cot_redirect(cot_url('admin', $urlParams, '', true));

/* =====================================================================
 * ОБРАБОТКА ДЕЙСТВИЯ 'update_checked'
 * ---------------------------------------------------------------------
 * Массовые операции над выбранными товарами (утверждение или удаление).
 * ===================================================================== */
} elseif ($a == 'update_checked') {
    /* -----------------------------------------------------------------
     * ПОЛУЧЕНИЕ ПАРАМЕТРОВ ИЗ POST
     * $paction — тип массовой операции ('validate' или 'delete').
     * $s — массив выбранных элементов (id => 1/on).
     * ----------------------------------------------------------------- */
    $paction = cot_import('paction', 'P', 'TXT');
    $s = cot_import('s', 'P', 'ARR');

    /* -----------------------------------------------------------------
     * ВЕТКА МАССОВОГО УТВЕРЖДЕНИЯ (paction == 'validate')
     * ----------------------------------------------------------------- */
    if ($paction == 'validate' && is_array($s)) {
        /* --------------------------------------------------------------
         * ПРОВЕРКА ТОКЕНА ДЛЯ POST-ЗАПРОСА
         * -------------------------------------------------------------- */
        cot_check_xp();

        /* --------------------------------------------------------------
         * ИНИЦИАЛИЗАЦИЯ СТРОК РЕЗУЛЬТАТОВ
         * $perelik — список успешно утверждённых товаров.
         * $notfoundet — список ошибок.
         * -------------------------------------------------------------- */
        $perelik = '';
        $notfoundet = '';

        /* --------------------------------------------------------------
         * ЦИКЛ ПО ВЫБРАННЫМ ТОВАРАМ
         * -------------------------------------------------------------- */
        foreach ($s as $i => $k) {
            /* ----------------------------------------------------------
             * Проверяем, что элемент отмечен (значение '1' или 'on')
             * ---------------------------------------------------------- */
            if ($s[$i] == '1' || $s[$i] == 'on') {
                /* === Hook === */
                /* ----------------------------------------------------
                 * ХУК market.admin.checked_validate
                 * Вызывается для каждого выбранного товара перед обработкой.
                 * ---------------------------------------------------- */
                foreach (cot_getextplugins('market.admin.checked_validate') as $pl) {
                    include $pl;
                }
                /* ===== */

                /* ----------------------------------------------------
                 * ПОЛУЧАЕМ ДАННЫЕ ТОВАРА ПО ID
                 * ---------------------------------------------------- */
                $sql_market = Cot::$db->query('SELECT * FROM ' . Cot::$db->market . ' WHERE fieldmrkt_id = ?', $i);

                /* ----------------------------------------------------
                 * ЕСЛИ ТОВАР СУЩЕСТВУЕТ
                 * ---------------------------------------------------- */
                if ($row = $sql_market->fetch()) {
                    $id = $row['fieldmrkt_id'];

                    /* -------------------------------------------------
                     * ПРОВЕРКА ПРАВ НА КАТЕГОРИЮ
                     * ------------------------------------------------- */
                    $usr['isadmin_local'] = cot_auth('market', $row['fieldmrkt_cat'], 'A');
                    cot_block($usr['isadmin_local']);

                    /* -------------------------------------------------
                     * ОБНОВЛЕНИЕ СТАТУСА НА STATE_PUBLISHED
                     * ------------------------------------------------- */
                    $sql_market = Cot::$db->update(
                        Cot::$db->market,
                        ['fieldmrkt_state' => MarketDictionary::STATE_PUBLISHED],
                        'fieldmrkt_id= ?',
                        $id
                    );

                    /* -------------------------------------------------
                     * ЗАПИСЬ В ЖУРНАЛ
                     * ------------------------------------------------- */
                    cot_log(
                        Cot::$L['Market'] . ' #' . $id . ' - ' . Cot::$L['adm_lang_market_queue_validated'],
                        'market',
                        'validate',
                        'done'
                    );

                    /* -------------------------------------------------
                     * ОЧИСТКА КЭША СТРАНИЦЫ ТОВАРА И КАТЕГОРИИ
                     * ------------------------------------------------- */
                    if (Cot::$cache && Cot::$cfg['cache_market']) {
                        Cot::$cache->static->clearByUri(cot_market_url($row));
                        Cot::$cache->static->clearByUri(cot_url('market', ['c' => $row['fieldmrkt_cat']]));
                    }

                    /* -------------------------------------------------
                     * ДОБАВЛЯЕМ ID В СПИСОК УСПЕШНЫХ
                     * ------------------------------------------------- */
                    $perelik .= '#' . $id . ', ';
                } else {
                    /* -------------------------------------------------
                     * ЕСЛИ ТОВАР НЕ НАЙДЕН, ФИКСИРУЕМ ОШИБКУ
                     * ------------------------------------------------- */
                    $notfoundet .= '#' . $id . ' - ' . Cot::$L['Error'] . '<br  />';
                }
            }
        }

        /* --------------------------------------------------------------
         * ПОСЛЕ ЦИКЛА: ОЧИСТКА ОБЩЕГО КЭША (структура, индекс)
         * -------------------------------------------------------------- */
        if (Cot::$cache) {
            Cot::$cache->db->remove('structure', 'system');
            if (Cot::$cfg['cache_index']) {
                Cot::$cache->static->clear('index');
            }
        }

        /* --------------------------------------------------------------
         * ВЫВОД СООБЩЕНИЙ ОБ ОШИБКАХ, ЕСЛИ ЕСТЬ
         * -------------------------------------------------------------- */
        if (!empty($notfoundet)) {
            cot_error($notfoundet);
        }

        /* --------------------------------------------------------------
         * ВЫВОД СООБЩЕНИЯ ОБ УСПЕХЕ, ЕСЛИ ЕСТЬ УТВЕРЖДЁННЫЕ
         * -------------------------------------------------------------- */
        if (!empty($perelik)) {
            cot_message($perelik . ' - ' . Cot::$L['adm_lang_market_queue_validated']);
        }

        /* --------------------------------------------------------------
         * РЕДИРЕКТ НА СПИСОК
         * -------------------------------------------------------------- */
        cot_redirect(cot_url('admin', $urlParams, '', true));

    /* -----------------------------------------------------------------
     * ВЕТКА МАССОВОГО УДАЛЕНИЯ (paction == 'delete')
     * ----------------------------------------------------------------- */
    } elseif ($paction == 'delete' && is_array($s)) {
        /* --------------------------------------------------------------
         * ПРОВЕРКА ТОКЕНА ДЛЯ POST
         * -------------------------------------------------------------- */
        cot_check_xp();

        /* --------------------------------------------------------------
         * ИНИЦИАЛИЗАЦИЯ СТРОК РЕЗУЛЬТАТОВ
         * -------------------------------------------------------------- */
        $perelik = '';
        $notfoundet = '';

        /* --------------------------------------------------------------
         * ПОЛУЧАЕМ ЭКЗЕМПЛЯР СЕРВИСА УДАЛЕНИЯ
         * -------------------------------------------------------------- */
        $marketService = MarketControlService::getInstance();

        /* --------------------------------------------------------------
         * ЦИКЛ ПО ВЫБРАННЫМ ТОВАРАМ
         * -------------------------------------------------------------- */
        foreach ($s as $id => $k) {
            if ($s[$id] == '1' || $s[$id] == 'on') {
                /* === Hook === */
                /* ----------------------------------------------------
                 * ХУК market.admin.checked_delete
                 * ---------------------------------------------------- */
                foreach (cot_getextplugins('market.admin.checked_delete') as $pl) {
                    include $pl;
                }
                /* ===== */

                /* ----------------------------------------------------
                 * УДАЛЕНИЕ ТОВАРА ЧЕРЕЗ СЕРВИС
                 * ---------------------------------------------------- */
                $resultOrMessage = $marketService->delete((int) $id);

                /* ----------------------------------------------------
                 * ЕСЛИ УСПЕХ
                 * ---------------------------------------------------- */
                if ($resultOrMessage !== false) {
                    /* === Hook === */
                    /* ------------------------------------------------
                     * ХУК market.admin.delete.done
                     * ------------------------------------------------ */
                    foreach (cot_getextplugins('market.admin.delete.done') as $pl) {
                        include $pl;
                    }
                    /* ===== */

                    /* ------------------------------------------------
                     * ФОРМИРУЕМ СПИСОК УДАЛЁННЫХ
                     * ------------------------------------------------ */
                    if ($perelik !== '') {
                        $perelik .= ', ';
                    }
                    $perelik .= '#' . $id;
                } else {
                    /* ------------------------------------------------
                     * ЕСЛИ ОШИБКА
                     * ------------------------------------------------ */
                    $notfoundet .= '#'. $id . ' - ' . Cot::$L['Error'] . '<br  />';
                }
            }
        }

        /* --------------------------------------------------------------
         * ВЫВОД ОШИБОК, ЕСЛИ ЕСТЬ
         * -------------------------------------------------------------- */
        if (!empty($notfoundet)) {
            cot_error($notfoundet);
        }

        /* --------------------------------------------------------------
         * ВЫВОД СООБЩЕНИЯ ОБ УСПЕХЕ
         * -------------------------------------------------------------- */
        if (!empty($perelik)) {
            cot_message($perelik . ' - ' . Cot::$L['market_deleted']);
        }

        /* --------------------------------------------------------------
         * РЕДИРЕКТ НА СПИСОК
         * -------------------------------------------------------------- */
        cot_redirect(cot_url('admin', $urlParams, '', true));
    }
}
/* =====================================================================
 * ПОДСЧЁТ ОБЩЕГО КОЛИЧЕСТВА ТОВАРОВ
 * ---------------------------------------------------------------------
 * Выполняется запрос COUNT(*) для определения общего количества записей,
 * удовлетворяющих условиям $sqlwhere и параметрам $params.
 * COUNT(*) не использует алиасы, поэтому в $sqlwhere нет префикса p.
 * fetchColumn() возвращает число.
 * ===================================================================== */
$totalitems = Cot::$db->query(
    'SELECT COUNT(*) FROM ' . Cot::$db->market . ' WHERE ' . $sqlwhere,
    $params
)->fetchColumn();

/* =====================================================================
 * ГЕНЕРАЦИЯ ПАГИНАЦИИ
 * ---------------------------------------------------------------------
 * cot_pagenav() строит структуру постраничной навигации.
 * Параметры:
 *   'admin' — модуль,
 *   $common_params — строка дополнительных URL-параметров (без пагинации),
 *   $d — текущее смещение,
 *   $totalitems — общее количество элементов,
 *   Cot::$cfg['market']['marketmaxlistsperpageadmin'] — элементов на страницу,
 *   'd' — имя GET-параметра для смещения,
 *   '' — дополнительный якорь (пусто),
 *   Cot::$cfg['jquery'] && Cot::$cfg['turnajax'] — разрешение AJAX-пагинации.
 * ===================================================================== */
$pagenav = cot_pagenav(
    'admin',
    $common_params,
    $d,
    $totalitems,
    Cot::$cfg['market']['marketmaxlistsperpageadmin'],
    'd',
    '',
    Cot::$cfg['jquery'] && Cot::$cfg['turnajax']
);

/* =====================================================================
 * ЗАПРОС СПИСКА ТОВАРОВ
 * ---------------------------------------------------------------------
 * Выбираем все поля товара (p.*) и имя владельца (u.user_name).
 * LEFT JOIN с таблицей пользователей $db_users по ID владельца.
 * Применяем условия $sqlwhere, сортировку $sqlsorttype $sqlsortway,
 * ограничиваем выборку LIMIT $d, количество на страницу.
 * Параметры передаются в подготовленный запрос.
 * ===================================================================== */
$sql_market = Cot::$db->query(
    "SELECT p.*, u.user_name
    FROM $db_market as p
    LEFT JOIN $db_users AS u ON u.user_id = p.fieldmrkt_ownerid
    WHERE $sqlwhere
    ORDER BY $sqlsorttype $sqlsortway
    LIMIT $d, ".Cot::$cfg['market']['marketmaxlistsperpageadmin'],
    $params
);

/* =====================================================================
 * ПОЛУЧЕНИЕ СТРОК РЕЗУЛЬТАТА
 * ---------------------------------------------------------------------
 * Сбрасываем счётчик строк $ii (используется для чётности/нечётности
 * и подсчёта выведенных записей).
 * fetchAll() возвращает массив всех строк.
 * ===================================================================== */
$ii = 0;
$sqllist_rowset = $sql_market->fetchAll(); // Сохраняем результат для подсчёта

/* =====================================================================
 * ФОРМИРОВАНИЕ СООБЩЕНИЯ О РЕЗУЛЬТАТАХ ПОИСКА
 * ---------------------------------------------------------------------
 * Если поисковый запрос $sq не пустой, формируем строку $searchMsg.
 * $totalFound — общее количество найденных товаров (из COUNT(*)).
 * $currentPageCount — количество товаров на текущей странице ($ii).
 * Используются локализованные склонения и функции cot_declension().
 * ===================================================================== */
$searchMsg = '';
if ($sq !== '') {
    $totalFound = (int)$totalitems;
    $currentPageCount = $ii; // количество товаров на текущей странице
    if ($totalFound > 0) {
        // Склоняем слова "товар" для общего количества и текущей страницы
        $totalStr = cot_declension($totalFound, $Ls['market_declen_items_sq_found']);
        $currentStr = cot_declension($currentPageCount, $Ls['market_declen_items_sq_found']);
        // Формируем сообщение о найденных товарах
        $searchMsg = sprintf($L['market_search_found'], $totalStr, $currentStr, htmlspecialchars($sq));
    } else {
        // Если ничего не найдено
        $searchMsg = sprintf($L['market_search_none'], htmlspecialchars($sq));
    }
}

/* === Hook - Part1 : Set === */
/* =====================================================================
 * ХУК market.admin.loop (ЧАСТЬ 1: ПОЛУЧЕНИЕ ПЛАГИНОВ)
 * ---------------------------------------------------------------------
 * Получаем список плагинов, привязанных к хуку market.admin.loop.
 * Эти плагины будут выполняться для каждой строки товара.
 * ===================================================================== */
$extp = cot_getextplugins('market.admin.loop');
/* ===== */

/* =====================================================================
 * ЦИКЛ ПО ТОВАРАМ ДЛЯ ВЫВОДА В ШАБЛОН
 * ---------------------------------------------------------------------
 * Перебираем каждую строку из $sqllist_rowset (данные товара).
 * Для каждого товара:
 *   - вычисляем количество товаров в подкатегориях;
 *   - формируем URL товара;
 *   - генерируем теги;
 *   - выводим строку в шаблон.
 * ===================================================================== */
foreach ($sqllist_rowset as $row) {
    /* -----------------------------------------------------------------
     * ПОДСЧЁТ ТОВАРОВ В ПОДКАТЕГОРИЯХ
     * -----------------------------------------------------------------
     * $sub_count — количество товаров во всех подкатегориях категории товара.
     * Если категория существует в структуре, выполняем запрос SUM(structure_count)
     * по таблице структуры, где structure_path начинается с пути категории.
     * fetchColumn() возвращает сумму или null (преобразуется к 0).
     * ----------------------------------------------------------------- */
    $sub_count = 0;
    if (isset(Cot::$structure['market'][$row["fieldmrkt_cat"]])) {
        $sql_market_subcount = Cot::$db->query("SELECT SUM(structure_count) FROM $db_structure WHERE structure_path LIKE '" . Cot::$db->prep(Cot::$structure['market'][$row["fieldmrkt_cat"]]['rpath']) . "%'");
        $sub_count = $sql_market_subcount->fetchColumn();
    }

    /* -----------------------------------------------------------------
     * ФОРМИРОВАНИЕ URL ТОВАРА
     * -----------------------------------------------------------------
     * Используем код категории напрямую.
     * Если у товара есть алиас, ссылаемся по алиасу, иначе по ID.
     * $itemUrlParams — параметры для cot_url().
     * ----------------------------------------------------------------- */
    $itemUrlParams = ['c' => $row['fieldmrkt_cat']];
    if (!empty($row['fieldmrkt_alias'])) {
        $itemUrlParams['al'] = $row['fieldmrkt_alias'];
    } else {
        $itemUrlParams['id'] = $row['fieldmrkt_id'];
    }
    // Генерируем URL и сохраняем в $row['item_pageurl']
    $row['item_pageurl'] = cot_url('market', $itemUrlParams);

    /* -----------------------------------------------------------------
     * ГЕНЕРАЦИЯ ТЕГОВ ТОВАРА И ДОПОЛНИТЕЛЬНЫХ ПЕРЕМЕННЫХ
     * -----------------------------------------------------------------
     * cot_generate_markettags() создаёт массив тегов с префиксом ADMIN_MARKET_.
     * Затем вручную добавляем специфичные теги для админки: ссылки, владелец, счётчик.
     * ----------------------------------------------------------------- */
    // Генерируем основные теги товара (обрезанный текст 200 символов)
    $t->assign(cot_generate_markettags($row, 'ADMIN_MARKET_', 200, $usr['isadmin'], $cfg['homebreadcrumb']));

    // Добавляем специфичные теги
    $t->assign([
        'ADMIN_MARKET_ID_URL' => $row['item_pageurl'],
        'ADMIN_MARKET_OWNER' => cot_build_user($row['fieldmrkt_ownerid'], $row['user_name']),

        // Ссылка для утверждения товара с подтверждением
        'ADMIN_MARKET_URL_FOR_VALIDATED' => cot_confirm_url(
            cot_url('admin', $common_params . '&a=validate&id=' . $row['fieldmrkt_id'] . '&d=' . $durl . '&' . cot_xg()),
            'market',
            'market_confirm_validate'
        ),
        // Ссылка для снятия с публикации с подтверждением
        'ADMIN_MARKET_URL_FOR_UNVALIDATE' => cot_confirm_url(
            cot_url('admin', $common_params . '&a=unvalidate&id=' . $row['fieldmrkt_id'] . '&d=' . $durl . '&' . cot_xg()),
            'market',
            'market_confirm_unvalidate'
        ),
        // Ссылка для удаления с подтверждением
        'ADMIN_MARKET_URL_FOR_DELETED' => cot_confirm_url(
            cot_url('admin', $common_params . '&a=delete&id=' . $row['fieldmrkt_id'] . '&d=' . $durl . '&' . cot_xg()),
            'market',
            'market_confirm_delete'
        ),
        // Ссылка на редактирование товара
        'ADMIN_MARKET_URL_FOR_EDIT' => cot_url('market', 'm=edit&id=' . $row['fieldmrkt_id']),
        // Чётность строки (для zebra-стилей)
